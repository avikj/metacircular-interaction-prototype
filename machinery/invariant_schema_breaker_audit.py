def orbit_collisions(n):
    """All unordered pairs of distinct subgroups of Sym(n) sharing an orbit
    partition."""
    subgroups = sorted(all_subgroups(n), key=lambda g: (len(g), sorted(g)))
    pairs = []
    for i, g in enumerate(subgroups):
        for h in subgroups[i + 1:]:
            if orbit_partition(n, g) == orbit_partition(n, h):
                pairs.append((g, h))
    return pairs


