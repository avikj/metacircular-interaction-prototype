A_MATRIX = ((2, 0), (1, 0))
D_MATRIX = ((1, 0), (0, 0))


def mat_mul(p, q):
    return tuple(
        tuple(sum(p[i][k] * q[k][j] for k in range(2)) for j in range(2))
        for i in range(2)
    )


def det2(m):
    return m[0][0] * m[1][1] - m[0][1] * m[1][0]


def transporter_element(k, sign):
    """The complete transporter T(A, D), derived: U = [[k, 1-2k], [w, -2w]]
    with w = -sign since det U = -w; sign in {+1, -1} is det U."""
    w = -sign
    return ((k, 1 - 2 * k), (w, -2 * w))


def transporter_membership(u):
    """Exact membership test for T(A, D): unimodular and U A = D."""
    return abs(det2(u)) == 1 and mat_mul(u, A_MATRIX) == D_MATRIX


def transporter_is_complete(bound):
    """Every unimodular U with U A = D and entries bounded by ``bound`` is of
    the derived form transporter_element(k, sign); and conversely every
    derived element is a member.  The forward direction is proved symbolically
    in the docstring (v = 1-2u, z = -2w, det = -w); this replays it on a
    finite window as a guard against algebra slips."""
    found = []
    rng = range(-bound, bound + 1)
    for a in rng:
        for b in rng:
            for c in rng:
                for d in rng:
                    u = ((a, b), (c, d))
                    if transporter_membership(u):
                        found.append(u)
    derived = {
        transporter_element(k, sign)
        for k in range(-bound, bound + 1)
        for sign in (1, -1)
    }
    return set(found) <= derived and all(
        transporter_membership(u) for u in derived
    )


def stabilizer_element(b, e):
    """Full stabilizer of D under left multiplication by GL_2(Z):
    H D = D forces H = [[1, b], [0, e]] with e = +-1 (det = e)."""
    return ((1, b), (0, e))


def stabilizer_is_complete(bound):
    """Same finite-window replay of the symbolic stabilizer computation."""
    found = []
    rng = range(-bound, bound + 1)
    for a in rng:
        for b in rng:
            for c in rng:
                for d in rng:
                    h = ((a, b), (c, d))
                    if abs(det2(h)) == 1 and mat_mul(h, D_MATRIX) == D_MATRIX:
                        found.append(h)
    derived = {
        stabilizer_element(b, e)
        for b in range(-bound, bound + 1)
        for e in (1, -1)
    }
    return set(found) <= derived and all(
        abs(det2(h)) == 1 and mat_mul(h, D_MATRIX) == D_MATRIX
        for h in derived
    )


def torsor_bijection_holds(bound):
    """Stab(D) . U_0 = T(A, D) on a window: left multiplication by the full
    stabilizer maps the base reducer U_0 = [[0,1],[1,-2]] onto both
    determinant components."""
    u0 = ((0, 1), (1, -2))
    image = {
        mat_mul(stabilizer_element(b, e), u0)
        for b in range(-bound, bound + 1)
        for e in (1, -1)
    }
    target = {
        transporter_element(k, sign)
        # H_b with e=+1 sends U_0 to U_b (det -1); e=-1 gives det +1 family.
        for k in range(-bound, bound + 1)
        for sign in (1, -1)
    }
    return image == target and all(transporter_membership(u) for u in image)


def false_control_rejected():
    """A determinant-2 matrix reaching D would break the audit; verify the
    natural candidate fails membership."""
    control = ((2, -3), (0, 1))  # det = 2, nonunimodular
    return abs(det2(control)) == 2 and not transporter_membership(control)


def smith_invariants_2x2(m):
    """d1 = gcd of entries, d2 = |det| / d1 convention as elementary divisors
    (d1, d2) with d1 | d2 when det != 0; here det = 0 so d2 = 0."""
    from math import gcd
    entries = [abs(x) for row in m for x in row]
    d1 = 0
    for x in entries:
        d1 = gcd(d1, x)
    det = abs(det2(m))
    d2 = det // d1 if d1 and det else 0
    return (d1, d2)


def determinant_unrecoverable():
    """The strengthening: two transporter elements with the same source A,
    same target D, same Smith invariants of source and target, same strict
    pivot descent 2 -> 1, but determinants -1 and +1."""
    u_minus = transporter_element(0, -1)   # note's U_0, det -1
    u_plus = transporter_element(0, +1)    # undisplayed component, det +1
    same_endpoint = (mat_mul(u_minus, A_MATRIX) == D_MATRIX
                     == mat_mul(u_plus, A_MATRIX))
    same_invariants = (smith_invariants_2x2(A_MATRIX),
                       smith_invariants_2x2(D_MATRIX)) == ((1, 0), (1, 0))
    return (same_endpoint and same_invariants
            and det2(u_minus) == -1 and det2(u_plus) == 1)
