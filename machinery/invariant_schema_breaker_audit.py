from itertools import permutations


# ---------------------------------------------------------------------------
# Finite permutation actions, independent implementation
# ---------------------------------------------------------------------------

def compose(p, q):
    """(p o q)(i) = p(q(i)); permutations as tuples."""
    return tuple(p[q[i]] for i in range(len(p)))


def generated_group(n, generators):
    """Subgroup of Sym(n) generated by tuples, by closure."""
    identity = tuple(range(n))
    group = {identity}
    frontier = [identity]
    gens = [tuple(g) for g in generators]
    while frontier:
        g = frontier.pop()
        for s in gens:
            h = compose(s, g)
            if h not in group:
                group.add(h)
                frontier.append(h)
    return frozenset(group)


def orbit_partition(n, group):
    """Set of frozensets: orbits of the group on range(n)."""
    seen = set()
    blocks = []
    for x in range(n):
        if x in seen:
            continue
        orbit = {p[x] for p in group}
        seen |= orbit
        blocks.append(frozenset(orbit))
    return frozenset(blocks)


def block_of(partition, x):
    for b in partition:
        if x in b:
            return b
    raise ValueError(x)


def K_fix(n, partition):
    """All permutations fixing every block setwise (the note's return map)."""
    return frozenset(
        p for p in permutations(range(n))
        if all(block_of(partition, i) == block_of(partition, p[i])
               for i in range(n))
    )


def K_perm(n, partition):
    """Alternative return map: permutations preserving the partition as a
    set of blocks, allowed to permute blocks.  Audited and rejected."""
    return frozenset(
        p for p in permutations(range(n))
        if frozenset(frozenset(p[i] for i in b) for b in partition)
        == partition
    )


def refines(fine, coarse):
    """Partition order: every fine block inside some coarse block."""
    return all(any(b <= c for c in coarse) for b in fine)


def all_subgroups(n):
    """Every subgroup of Sym(n) (exhaustive; n <= 4 feasible, we use n <= 3)."""
    elements = list(permutations(range(n)))
    subgroups = set()
    # generate from every subset of a generating pool; for n <= 3 the whole
    # element list is a fine pool and closure is cheap.
    from itertools import combinations
    for r in range(len(elements) + 1):
        for gens in combinations(elements, r if r <= 3 else 3):
            subgroups.add(generated_group(n, gens))
        if r > 3:
            break
    return subgroups


# ---------------------------------------------------------------------------
# Audit 1: Galois connection and envelope identities, exhaustive on n <= 3
# ---------------------------------------------------------------------------

def all_partitions(n):
    """All set partitions of range(n)."""
    if n == 0:
        return [frozenset()]
    parts = []

    def rec(i, current):
        if i == n:
            parts.append(frozenset(frozenset(b) for b in current))
            return
        for b in current:
            b.add(i)
            rec(i + 1, current)
            b.remove(i)
        current.append({i})
        rec(i + 1, current)
        current.pop()

    rec(0, [])
    return parts


def galois_adjunction_holds(n):
    """Check  G <= K(E)  iff  E_G refines E,  for every subgroup G and
    partition E of range(n)."""
    for group in all_subgroups(n):
        e_g = orbit_partition(n, group)
        for e in all_partitions(n):
            left = group <= K_fix(n, e)
            right = refines(e_g, e)
            if left != right:
                return False
    return True


def envelope_identities_hold(n, generators):
    """The three identities of the source note for one generating set."""
    group = generated_group(n, generators)
    e_g = orbit_partition(n, group)
    k = K_fix(n, e_g)
    ident1 = group <= k
    ident2 = orbit_partition(n, k) == e_g
    ident3 = K_fix(n, orbit_partition(n, k)) == k
    return ident1 and ident2 and ident3


def block_permuting_counterexample():
    """K_perm fails identity (2) on two points with the discrete partition:
    it merges the two singleton blocks.  Returns the witness data."""
    n = 2
    discrete = frozenset({frozenset({0}), frozenset({1})})
    k = K_perm(n, discrete)
    return {
        "partition": discrete,
        "K_perm_order": len(k),
        "orbit_partition": orbit_partition(n, k),
        "identity2_holds": orbit_partition(n, k) == discrete,
    }


