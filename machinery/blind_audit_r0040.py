def S_pk_polynomial(k):
    """S(p^k) as an exact polynomial in Z[p] (dict {i: coeff} for p^i),
    from the c-psi sum with symbolic psi(p^t) = p^t + p^{t-1} (t>=1),
    psi(1) = 1 — my own derivation route, no closed form used."""
    out = {}
    for j in range(k // 2 + 1):
        t = k - 2 * j
        if t == 0:
            terms = {0: 1}
        else:
            terms = {t: 1, t - 1: 1}
        for i, c in terms.items():
            out[i + j] = out.get(i + j, 0) + c
    return {i: c for i, c in out.items() if c != 0}


def S_pk_closed_polynomial(k):
    """The claimed closed form (p^{k+1}+p^k-p^{ceil(k/2)}-p^{floor(k/2)})/(p-1)
    as an exact polynomial in Z[p], via exact univariate division."""
    num = {}
    for i, c in ((k + 1, 1), (k, 1), ((k + 1) // 2, -1), (k // 2, -1)):
        num[i] = num.get(i, 0) + c  # additive build: exponents can collide
    num = {i: c for i, c in num.items() if c != 0}
    # divide by (p - 1) exactly
    quo = {}
    rem = dict(num)
    while rem:
        deg = max(rem)
        if deg == 0:
            break
        c = rem[deg]
        quo[deg - 1] = quo.get(deg - 1, 0) + c
        rem[deg - 1] = rem.get(deg - 1, 0) + c
        del rem[deg]
        rem = {i: v for i, v in rem.items() if v != 0}
    assert not rem, "not divisible by (p-1): %r" % rem
    return quo
