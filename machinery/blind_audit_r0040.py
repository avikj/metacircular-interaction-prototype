def factorize(n):
    out = []
    p = 2
    while p * p <= n:
        if n % p == 0:
            k = 0
            while n % p == 0:
                n //= p
                k += 1
            out.append((p, k))
        p += 1
    if n > 1:
        out.append((n, 1))
    return out


def phi(n):
    result = n
    for p, _ in factorize(n):
        result = result // p * (p - 1)
    return result


def sigma_k(n, k):
    return sum(d ** k for d in divisors(n))


def jordan2(n):
    """Jordan totient J_2(n) = n^2 prod_{p|n} (1 - 1/p^2), exactly."""
    result = n * n
    for p, _ in factorize(n):
        result = result // (p * p) * (p * p - 1)
    return result


def square_divisor_roots(m):
    """All c >= 1 with c^2 | m."""
    return [c for c in range(1, isqrt(m) + 1) if m % (c * c) == 0]


