def phi_map(basis):
    """Phi(L) = (e_1, canonical HNF of (1/e_1) L), computed WITHOUT the
    claimed always-reduced shortcut: divide the columns and re-canonicalize
    from scratch with hnf_of_columns."""
    c = content(basis)
    cols = basis_columns(basis)
    divided = [(x // c, y // c) for (x, y) in cols]
    return c, hnf_of_columns(divided)


def phi_inverse(c, cyclic_basis):
    """(c, L') -> c L', re-canonicalized independently."""
    cols = [(c * x, c * y) for (x, y) in basis_columns(cyclic_basis)]
    return hnf_of_columns(cols)


