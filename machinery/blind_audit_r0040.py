def S_direct(m):
    return sum(content(basis) for basis in hnf_bases(m))


def S_c_psi(m):
    return sum(c * psi(m // (c * c)) for c in square_divisor_roots(m))


def S_phi_sigma(m):
    return sum(phi(c) * sigma1(m // (c * c)) for c in square_divisor_roots(m))


def S_prime_power_closed(p, k):
    num = p ** (k + 1) + p ** k - p ** ((k + 1) // 2) - p ** (k // 2)
    assert num % (p - 1) == 0
    return num // (p - 1)


def S_multiplicative(m):
    result = 1
    for p, k in factorize(m):
        result *= S_prime_power_closed(p, k)
    return result


