# bivariate polynomial arithmetic over Z, variables (p, x), for the
# Euler-factor identity — dict {(i, j): coeff} meaning coeff * p^i x^j
# ---------------------------------------------------------------------------

def poly_mul(f, g):
    out = {}
    for (i1, j1), c1 in f.items():
        for (i2, j2), c2 in g.items():
            key = (i1 + i2, j1 + j2)
            out[key] = out.get(key, 0) + c1 * c2
    return {k: v for k, v in out.items() if v != 0}


def poly_sub(f, g):
    out = dict(f)
    for k, v in g.items():
        out[k] = out.get(k, 0) - v
    return {k: v for k, v in out.items() if v != 0}


