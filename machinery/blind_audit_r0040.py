def sublattices_direct(m):
    """All index-m sublattices of Z^2, enumerated WITHOUT Hermite theory:
    every such L contains m Z^2, so L <-> subgroup of (Z/m)^2 of order m.
    Brute-force subgroup generation over all generator pairs; each lattice
    is returned as its canonical HNF computed by hnf_of_columns from the
    lifted generators plus (m,0),(0,m)."""
    n = m
    elems = [(x, y) for x in range(n) for y in range(n)]
    lattices = set()
    for v in elems:
        for w in elems:
            # generate subgroup <v, w> (no pruning: pairs inside a large
            # subgroup generate SUB-subgroups, so any pair-level dedup
            # across groups is unsound)
            group = {(0, 0)}
            frontier = [(0, 0)]
            while frontier:
                g0 = frontier.pop()
                for h in (v, w):
                    ng = ((g0[0] + h[0]) % n, (g0[1] + h[1]) % n)
                    if ng not in group:
                        group.add(ng)
                        frontier.append(ng)
            if len(group) == m:  # index m^2/m = m in (Z/m)^2 -> index m in Z^2
                cols = [list(g) for g in group] + [[m, 0], [0, m]]
                lattices.add(hnf_of_columns(cols))
    return lattices


