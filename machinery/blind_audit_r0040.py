def hnf_of_columns(cols):
    """Canonical Hermite basis ((a,0),(b,d)) of the lattice generated by the
    given list of integer column vectors (must have full rank).  Pure
    integer column operations (right GL_2(Z) action fixes the lattice)."""
    cols = [list(c) for c in cols]
    # fold everything into two columns by repeated gcd elimination on row 0
    work = [c for c in cols if c != [0, 0]]
    assert work, "zero lattice"
    # eliminate row-0 entries down to a single column with nonzero row 0
    # using pairwise Euclid; keep all columns (they still generate).
    changed = True
    while changed:
        changed = False
        # pick pivot: nonzero minimal |row0|
        piv = None
        for i, c in enumerate(work):
            if c[0] != 0 and (piv is None or abs(c[0]) < abs(work[piv][0])):
                piv = i
        assert piv is not None, "rank < 2 in row 0? not full rank"
        for i, c in enumerate(work):
            if i != piv and c[0] != 0:
                q = c[0] // work[piv][0]
                c[0] -= q * work[piv][0]
                c[1] -= q * work[piv][1]
                changed = True
    first = work.pop(piv)
    # remaining columns have row0 == 0; reduce their row 1 to one gcd
    g = 0
    for c in work:
        assert c[0] == 0
        g = gcd(g, c[1])
    assert g != 0, "not full rank"
    a, b = first[0], first[1]
    d = g
    if a < 0:
        a, b = -a, -b
    if d < 0:
        d = -d
    b %= d
    return ((a, 0), (b, d))


def basis_columns(basis):
    """Columns (a,b) and (0,d) of Hermite basis ((a,0),(b,d))."""
    (a, _), (b, d) = basis
    return [(a, b), (0, d)]


def scale_basis(basis, c):
    (a, _), (b, d) = basis
    return ((c * a, 0), (c * b, c * d))


def divide_basis(basis, c):
    (a, _), (b, d) = basis
    assert a % c == 0 and b % c == 0 and d % c == 0
    return ((a // c, 0), (b // c, d // c))


def index_of(basis):
    (a, _), (b, d) = basis
    return a * d


def is_reduced_hnf(basis):
    (a, _), (b, d) = basis
    return a >= 1 and d >= 1 and 0 <= b < d


