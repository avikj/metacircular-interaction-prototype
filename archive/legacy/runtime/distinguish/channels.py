def digit_channel(index: int) -> Channel:
    def fn(digits: Sequence[int], counter: StepCounter) -> int:
        counter.tick("digit-read")
        return digits[index]

    return Channel("digit_%d" % index, 1, fn)


def residue_channel(base: int, length: int, modulus: int) -> Channel:
    """``L(w) mod modulus``, reading only the digits that can matter.

    ``truncation_length`` returns the smallest ``k`` with ``b**k == 0 mod m``;
    beyond that point higher digits contribute nothing, so the channel reads
    ``k`` digits, not ``n``.  For ``b = 6``, ``m = 8`` this is 3 digits because
    ``6**3 = 216 = 8 * 27``.  The declared cost equals the actual reads.
    """
    top = truncation_length(base, modulus, length)

    def fn(digits: Sequence[int], counter: StepCounter) -> int:
        return horner_mod(digits, base, modulus, top, counter)

    return Channel("res_%d" % modulus, top, fn)


def digit_sum_mod_channel(length: int, modulus: int) -> Channel:
    def fn(digits: Sequence[int], counter: StepCounter) -> int:
        acc = 0
        for index in range(length):
            counter.tick("digit-read")
            acc += digits[index]
        return acc % modulus

    return Channel("digitsum_mod_%d" % modulus, length, fn)


def alternating_sum_mod_channel(length: int, modulus: int) -> Channel:
    def fn(digits: Sequence[int], counter: StepCounter) -> int:
        acc = 0
        sign = 1
        for index in range(length):
            counter.tick("digit-read")
            acc += sign * digits[index]
            sign = -sign
        return acc % modulus

    return Channel("altsum_mod_%d" % modulus, length, fn)


def palindrome_channel(length: int) -> Channel:
    """Indicator of ``Fix(D)`` -- the palindromes (DIGIT_CRYSTAL Thm 3.4)."""
    half = (length + 1) // 2

    def fn(digits: Sequence[int], counter: StepCounter) -> int:
        for index in range(half):
            counter.tick("digit-read")
            if digits[index] != digits[length - 1 - index]:
                return 0
        return 1

    return Channel("is_palindrome", half, fn)


def valuation_channel(length: int) -> Channel:
    """``v_b`` -- the number of trailing zero digits (DIGIT_CRYSTAL §0)."""

    def fn(digits: Sequence[int], counter: StepCounter) -> int:
        count = 0
        for index in range(length):
            counter.tick("digit-read")
            if digits[index] != 0:
                break
            count += 1
        return count

    return Channel("valuation", length, fn)


def zero_count_channel(length: int) -> Channel:
    def fn(digits: Sequence[int], counter: StepCounter) -> int:
        count = 0
        for index in range(length):
            counter.tick("digit-read")
            if digits[index] == 0:
                count += 1
        return count

    return Channel("zero_count", length, fn)


def reversed_residue_channel(base: int, length: int, modulus: int) -> Channel:
    """``L(rho(w)) mod modulus`` -- reads the word through the reversal ``D``.

    This channel is what the demo's falsification task needs and the declared
    task family never does; it exists in the library so that the recompilation
    after the new task arrives is a search, not a hand-placed answer.
    """

    def fn(digits: Sequence[int], counter: StepCounter) -> int:
        acc = 0
        for index in range(length):
            counter.tick("digit-read")
            acc = (acc * base + digits[index]) % modulus
        return acc

    return Channel("rev_res_%d" % modulus, length, fn)


def prime_powers_dividing(value: int, limit: int) -> tuple[int, ...]:
    """Every prime power ``p**j > 1`` dividing ``value``, ascending by prime."""
    out: list[int] = []
    rest = value
    factor = 2
    while factor * factor <= rest:
        if rest % factor == 0:
            exponent = 0
            while rest % factor == 0:
                rest //= factor
                exponent += 1
            power = factor
            for _ in range(min(exponent, limit)):
                out.append(power)
                power *= factor
        factor += 1
    if rest > 1:
        out.append(rest)
    return tuple(out)


def standard_library(system: DigitWordSystem) -> tuple[Channel, ...]:
    """The invariant library for a digit-word system, in canonical order."""
    base, length = system.base, system.length
    channels: list[Channel] = []
    for index in range(length):
        channels.append(digit_channel(index))
    for power in prime_powers_dividing(system.size, length):
        channels.append(residue_channel(base, length, power))
    for modulus in (5, 7):
        if system.size % modulus != 0:
            channels.append(residue_channel(base, length, modulus))
    for modulus in (2, 3, 5):
        channels.append(digit_sum_mod_channel(length, modulus))
    channels.append(alternating_sum_mod_channel(length, base + 1))
    channels.append(palindrome_channel(length))
    channels.append(valuation_channel(length))
    channels.append(zero_count_channel(length))
    return tuple(channels)


def channel_values(
    system: DigitWordSystem,
    channels: Sequence[Channel],
    counter: StepCounter,
) -> dict[str, tuple[int, ...]]:
    """Compile-time value arrays: one entry per state per channel."""
    silent = NullCounter()
    columns: dict[str, list[int]] = {channel.name: [0] * system.size for channel in channels}
    counter.tick("compile-state-visit", system.size * len(channels))
    for value in range(system.size):
        word = system.digits(value)
        for channel in channels:
            columns[channel.name][value] = channel.eval_word(word, silent)
    return {name: tuple(column) for name, column in columns.items()}


