"""The invariant/channel library and the minimal-separating-channel search.

CRYSTAL.md §3.2 step 4 says "search the invariant library for a *minimal*
channel separating the collision while preserving previously discharged
tasks".  "Minimal" is ambiguous and the ambiguity is where such systems
usually lie, so this module states which is meant, every time:

``minimum_cardinality_set``
    **Exact minimum cardinality.**  Subsets of the library are enumerated by
    increasing size and the first size that admits a solution is returned.
    This is exact -- an exhaustive proof that no smaller subset works comes
    free with the enumeration -- and exponential; it is guarded by an explicit
    subset budget and raises ``SearchBudgetExceeded`` rather than silently
    degrading.  Ties at the minimum size are broken deterministically by
    ``(number of induced classes, total declared digit reads, names)``.

``greedy_set``
    **Greedy set cover.**  Returned results are labelled ``greedy`` and carry
    the standard approximation bound: for a constraint set of size ``P``,
    ``|greedy| <= H(P) * OPT`` where ``H(P) = 1 + 1/2 + ... + 1/P``, and this
    is tight for set cover.  A greedy result is never called "minimal" without
    that qualification.

``inclusion_minimal_set``
    **Minimal under inclusion.**  Repeatedly drops any single channel whose
    removal preserves the requirement.  The result admits no removable member
    (that is the check the tests plant a false positive against) but is *not*
    claimed to be minimum cardinality.  This is CRYSTAL.md §3.2 step 6 --
    redundant-channel removal -- and is what deletes a null channel.

Two requirement kinds are supported, and they are different claims:

* ``PairRequirement`` -- separate a finite list of collision pairs.  This is
  what the compile loop can actually see at any moment.
* ``PartitionRequirement`` -- refine a whole target partition.  This is the
  global claim, checkable in ``O(|S|)`` per subset because refinement of a
  partition is a class-count identity, not a pair enumeration.

The library itself is generated by a uniform rule so the search is not rigged:
single-digit readouts, residues at every prime power dividing ``b**n`` up to
the length bound plus two primes that do *not* divide it, digit-sum invariants,
palindromy (the fixed-point set of the reversal ``D``, DIGIT_CRYSTAL Thm 3.4),
the ``b``-adic valuation, and a zero count.  Nothing in the library is the
answer to a declared task by construction.
"""

from __future__ import annotations

from itertools import combinations
from typing import Sequence

from .observe import Channel, DigitWordSystem, NullCounter, StepCounter, horner_mod, truncation_length


class SearchBudgetExceeded(Exception):
    """Raised when exact minimum-cardinality search would exceed its budget."""


