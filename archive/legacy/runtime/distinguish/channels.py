class ChannelSearchResult:
    """A channel set plus the exact strength of the minimality claim."""

    __slots__ = ("names", "claim", "detail", "subsets_tested", "n_classes")

    def __init__(self, names: Sequence[str], claim: str, detail: str, subsets_tested: int, n_classes: int) -> None:
        self.names = tuple(names)
        self.claim = claim
        self.detail = detail
        self.subsets_tested = subsets_tested
        self.n_classes = n_classes

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return "ChannelSearchResult(%r, claim=%s, classes=%d)" % (list(self.names), self.claim, self.n_classes)


def _class_count(columns: Sequence[Sequence[int]], n_states: int) -> int:
    if not columns:
        return 1
    return len(set(zip(*columns)))


def minimum_cardinality_set(
    library: Sequence[Channel],
    values: dict[str, tuple[int, ...]],
    requirement,
    counter: StepCounter,
    budget: int = 400000,
    max_size: int | None = None,
) -> ChannelSearchResult:
    """Exact minimum-cardinality channel set satisfying ``requirement``.

    Enumerates subsets by increasing size; the first size with a solution is
    the minimum, and the enumeration of all smaller sizes *is* the proof that
    nothing smaller works.  Deterministic tie-break at the minimum size:
    fewest induced classes, then fewest declared digit reads, then names.
    """
    names = [channel.name for channel in library]
    reads = {channel.name: channel.reads for channel in library}
    n_states = len(values[names[0]]) if names else 0
    limit = len(library) if max_size is None else min(max_size, len(library))
    tested = 0
    for size in range(0, limit + 1):
        winners: list[tuple[int, int, tuple[str, ...]]] = []
        for combo in combinations(range(len(library)), size):
            tested += 1
            if tested > budget:
                raise SearchBudgetExceeded(
                    "exact search exceeded %d subsets at size %d; use greedy_set and state the bound" % (budget, size)
                )
            counter.tick("subset-test")
            chosen = tuple(names[i] for i in combo)
            columns = [values[name] for name in chosen]
            if requirement.satisfied_by(columns, counter):
                winners.append((_class_count(columns, n_states), sum(reads[name] for name in chosen), chosen))
        if winners:
            winners.sort()
            classes, _, chosen = winners[0]
            return ChannelSearchResult(
                chosen,
                "exact-minimum-cardinality",
                "no subset of size < %d satisfies the requirement (%d subsets enumerated)" % (size, tested),
                tested,
                classes,
            )
    raise ValueError("no subset of the library satisfies the requirement")


def harmonic_bound_numerator_denominator(n: int) -> tuple[int, int]:
    """``H(n) = 1 + 1/2 + ... + 1/n`` as an exact fraction.  No floating point."""
    num, den = 0, 1
    for k in range(1, n + 1):
        num, den = num * k + den, den * k
        g = _gcd(num, den)
        num, den = num // g, den // g
    return num, den


def harmonic_ceiling(n: int) -> int:
    """The least integer ``k`` with ``H(n) <= k``.  Exact, no floating point."""
    num, den = harmonic_bound_numerator_denominator(max(1, n))
    return -((-num) // den)


def _gcd(a: int, b: int) -> int:
    while b:
        a, b = b, a % b
    return a if a > 0 else 1


def greedy_set(
    library: Sequence[Channel],
    values: dict[str, tuple[int, ...]],
    requirement: PairRequirement,
    counter: StepCounter,
) -> ChannelSearchResult:
    """Greedy set cover over collision pairs.  NOT claimed to be minimum.

    Bound: ``|greedy| <= H(P) * OPT`` with ``P = |pairs|`` and ``H`` the
    harmonic number, computed here as an exact fraction.  Ties are broken by
    (most pairs covered, fewest declared reads, name).
    """
    if requirement.kind != "pairs":
        raise TypeError("greedy_set covers pair requirements only")
    uncovered = set(range(len(requirement.pairs)))
    coverage = {
        channel.name: requirement.covered_by_channel(values[channel.name], counter) for channel in library
    }
    reads = {channel.name: channel.reads for channel in library}
    chosen: list[str] = []
    while uncovered:
        best = None
        for channel in library:
            counter.tick("subset-test")
            gain = len(coverage[channel.name] & uncovered)
            if gain == 0:
                continue
            key = (-gain, reads[channel.name], channel.name)
            if best is None or key < best[0]:
                best = (key, channel.name)
        if best is None:
            raise ValueError("library cannot separate every pair")
        chosen.append(best[1])
        uncovered -= coverage[best[1]]
    columns = [values[name] for name in chosen]
    ceiling = harmonic_ceiling(len(requirement.pairs))
    return ChannelSearchResult(
        tuple(chosen),
        "greedy",
        "|C| <= H(%d) * OPT <= %d * OPT  (H exact, ceiling shown)" % (len(requirement.pairs), ceiling),
        len(library),
        _class_count(columns, len(values[library[0].name])),
    )


def inclusion_minimal_set(
    names: Sequence[str],
    values: dict[str, tuple[int, ...]],
    requirement,
    counter: StepCounter,
    reads: dict[str, int] | None = None,
) -> tuple[tuple[str, ...], tuple[str, ...]]:
    """Drop every channel whose removal preserves the requirement.

    CRYSTAL.md §3.2 step 6.  Returns ``(kept, dropped)``.  ``kept`` is minimal
    **under inclusion** -- no single member can be removed -- and is *not*
    claimed to be minimum cardinality.  Removal order is deterministic:
    most declared digit reads first, then name, so the expensive redundant
    channels go first.
    """
    reads = reads or {name: 0 for name in names}
    current = list(names)
    dropped: list[str] = []
    order = sorted(names, key=lambda name: (-reads.get(name, 0), name))
    for name in order:
        trial = [other for other in current if other != name]
        counter.tick("subset-test")
        if requirement.satisfied_by([values[other] for other in trial], counter):
            current = trial
            dropped.append(name)
    return tuple(current), tuple(dropped)


def is_inclusion_minimal(
    names: Sequence[str],
    values: dict[str, tuple[int, ...]],
    requirement,
    counter: StepCounter,
) -> tuple[bool, tuple[str, ...]]:
    """Check the inclusion-minimality claim; return any removable members."""
    removable: list[str] = []
    for name in names:
        trial = [other for other in names if other != name]
        counter.tick("subset-test")
        if requirement.satisfied_by([values[other] for other in trial], counter):
            removable.append(name)
    return (len(removable) == 0), tuple(removable)
