class PairRequirement:
    """Separate a finite list of state pairs (the collisions found so far)."""

    kind = "pairs"

    __slots__ = ("pairs",)

    def __init__(self, pairs: Sequence[tuple[int, int]]) -> None:
        self.pairs = tuple(pairs)

    @property
    def size(self) -> int:
        return len(self.pairs)

    def satisfied_by(self, columns: Sequence[Sequence[int]], counter: StepCounter) -> bool:
        for x, y in self.pairs:
            counter.tick("pair-visit")
            separated = False
            for column in columns:
                if column[x] != column[y]:
                    separated = True
                    break
            if not separated:
                return False
        return True

    def covered_by_channel(self, column: Sequence[int], counter: StepCounter) -> frozenset:
        covered = set()
        for index, (x, y) in enumerate(self.pairs):
            counter.tick("pair-visit")
            if column[x] != column[y]:
                covered.add(index)
        return frozenset(covered)


class PartitionRequirement:
    """Refine a target partition -- the global sufficiency claim.

    ``columns`` refine ``target`` exactly when the number of distinct joint
    keys equals the number of distinct ``(key, target)`` pairs, which is an
    ``O(|S|)`` test with no pair enumeration.
    """

    kind = "partition"

    __slots__ = ("target", "n_states")

    def __init__(self, target: Sequence[int]) -> None:
        self.target = tuple(target)
        self.n_states = len(self.target)

    @property
    def size(self) -> int:
        return self.n_states

    def satisfied_by(self, columns: Sequence[Sequence[int]], counter: StepCounter) -> bool:
        counter.tick("state-visit", self.n_states)
        if not columns:
            return len(set(self.target)) <= 1
        joint = set(zip(*columns))
        with_target = set(zip(*columns, self.target))
        return len(joint) == len(with_target)


