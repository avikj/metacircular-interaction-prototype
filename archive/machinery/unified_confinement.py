    print(f"  {'p':>3} {'k':>3} {'gens':>10} {'index':>6} {'e*p^(l-lmin)':>13} "
          f"{'e':>3} {'l':>3} {'lmin':>5}")
    cases = [(3, 4, (2,)), (3, 4, (4,)), (5, 3, (2,)), (5, 3, (4,)),
             (5, 4, (7,)), (7, 3, (2,)), (7, 4, (3,)), (11, 3, (3,)),
             (13, 3, (5,)), (2, 8, (3,)), (2, 8, (5,)), (2, 8, (7,)),
             (2, 8, (17,)), (2, 10, (31,)), (2, 8, (3, 5))]
    for p, k, gens in cases:
        record = unified_index(gens, p, k)
        assert record.index == record.predicted, (p, k, gens)
        print(f"  {record.p:>3} {record.k:>3} {str(record.generators):>10} "
              f"{record.index:>6} {record.predicted:>13} "
              f"{record.tame_index:>3} {record.level:>3} "
              f"{record.minimal_level:>5}")

