selfTest :: [(String, Bool)]
selfTest =
  [ ( "a line number is refused, and the defect names the position"
    , case pathya "machine/machine.log:146" "x = (xmaxx)" of
        Left (Sthana "machine/machine.log" 146) -> True
        _ -> False )

  , ( "a HEAD-relative commit is refused as shirsha"
    , case baddha "HEAD~3" "machine/Naya.hs" "content" of
