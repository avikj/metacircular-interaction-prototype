-- MulaPramana_ACitationNamesAFixedObjectOrItIsNotOne
--
-- मूल-प्रमाण — the root-attestation.  A citation is an instrument of
-- knowledge only if the thing it names can be gone back to.  This module
-- makes the citations that CANNOT be gone back to unconstructible, and
-- resolves the ones that can against the repository.
--
--     runghc -imachine machine/MulaPramanaRun_CheckEveryCitationInTheRecord.hs
--
-- ────────────────────────────────────────────────────────────────────
-- WHAT A CITATION IS, IN THE TRADITION THAT NAMED IT.
--
-- Gautama, Nyāyasūtra 1.1.7 (c. 2nd c. CE): `āptopadeśaḥ śabdaḥ` — verbal
-- testimony is the instruction of a trustworthy speaker.  The whole force
-- of śabda-pramāṇa is that there IS an āpta and that one can be returned
-- to him.  A citation is śabda in written form, and it inherits that
-- condition exactly: `machine/machine.log:146` names no āpta, because the
-- file is regenerated by the engine on every run and is gitignored.  Line
-- 146 was one sentence on 2026-08-18 and is a different sentence today.
-- The citation did not become inaccurate.  It never named anything.
--
-- Kumārila Bhaṭṭa, Ślokavārttika, Abhāvapariccheda (c. 7th c. CE), on
-- yogya-anupalabdhi: "not seen" is no pramāṇa; "not seen WHERE IT WOULD BE
-- SEEN" is.  So the resolver below separates three outcomes and never two:
-- the object is there (Sthira), the object is NOT there in a place fit to
-- hold it (Nashta — a real denial), and there is no place fit to hold it
-- at all (Achalya — silence, and silence is not a denial).
--
-- NOT CLAIMED: that Gautama or Kumārila wrote a citation checker, or
-- discussed version control.  What is taken is the condition on śabda and
-- the fitness condition on absence.  The application is this repository's.
--
-- ────────────────────────────────────────────────────────────────────
-- THE THREE OUTCOMES WERE ENFORCED IN THE TYPE AND DEFEATED IN THE READ.
-- 2026-08-22.  Recorded here and not in `machine/dosa.lekha`, whose chain
-- is broken from record 0040 and whose `write` refuses to append;
-- resealing it is the edit that organ was founded to forbid.
--
-- `Sthiti` has three constructors and its own comment says why.  Two
-- helpers underneath it had two values each, and both of them fed the
-- distinction the type exists to hold:
--
--   readFileOr p = do (ec, out, _) <- readProcessWithExitCode "cat" [p] ""
--                     pure (if ec == ExitSuccess then out else "")
--   tracked    p = do (c, _, _) <- git [...]; pure (c == ExitSuccess)
--
-- `""` is not inert.  It reaches `q \`isInfixOf\` w`, which is False, which
-- is `Nashta` — a DENIAL, "the citation rotted", issued about a file that
-- was never opened.  That is precisely the non-apprehension from an unfit
-- looking that the paragraph above cites Kumārila to forbid, committed by
-- the module that cites him.  In `Niyama` it lands one step further in:
-- `hits = []`, so the outcome is `Achalya` — right constructor, wrong
-- reason, "no line of p contains a", which asserts a fit looking that
-- found nothing.
--
-- The discarded slot in both is the child's own sentence, dropped at the
-- pattern `(ec, out, _)` / `(c, _, _)` and, in the first, a second time by
-- the `if`.  `cat` had already said "Permission denied"; `git` had already
-- said "fatal: not a git repository".
--
-- EXHIBITED, NOT ASSERTED.  A one-file clone, `f.txt` holding `alpha`,
-- committed, then `chmod 000 f.txt`.  Against the code at HEAD before this
-- commit:
--
--   pathya f.txt "alpha"  -> NASHTA  "present at HEAD, absent in the working
--                                     tree -- an uncommitted edit removed it"
--   pathya f.txt "beta"   -> NASHTA  "the pattern is absent from f.txt"
--   the same, run from outside any clone
--                         -> ACHALYA "f.txt is not tracked -- no commit fixes
--                                     its bytes"   (git had exited 128)
--
-- No edit removed anything, the pattern was never looked for, and the path
-- is tracked.  All three are now `Achalya` carrying the child's sentence.
--
-- MEASURED, so 1 is a finding and not a guess: `git ls-files
-- --error-unmatch` exits 1 on an untracked path and 128 outside a
-- repository, so 1 is git answering and anything else is git declining.
-- A child that cannot be launched at all is caught rather than thrown, for
-- the same reason: an exception out of `cat` would kill the census over the
-- whole record instead of marking one line.
--
-- `selfTest` is 13/13 and the census over `machine/mula.pramana` is
-- byte-identical before and after — every citation in the record resolves
-- through a looking that WAS fit, which is why the defect had never shown.
--
-- ────────────────────────────────────────────────────────────────────
-- WHY BYTE-EQUALITY OF A QUOTED PATTERN, AND WHOSE DISPUTE THAT IS.
--
-- `Pathya` and `Baddha` resolve by asking whether a verbatim string occurs
-- in a file.  That is byte equality, not sameness of meaning, and deciding
-- sameness of meaning is a live dispute between two schools that reject
-- each other's account of it.  Naming the schools, as required:
--
--   The BUDDHIST PRAMĀṆA school.  Dignāga, Pramāṇasamuccaya V (c. 480–540
--   CE): a word's content is anyāpoha, the exclusion of what it is not;
--   there is no positive universal for it to denote.  Read that way a
--   quoted byte-pattern is the ideal citation object, because it makes no
--   positive claim whatever — it excludes every other byte string and
--   asserts nothing beyond the exclusion.  Śāntarakṣita, Tattvasaṃgraha
--   (c. 725–788 CE), defends this against the objections below.
--
--   The NAIYĀYIKAS.  Uddyotakara, Nyāyavārttika (c. 550–610 CE), and
--   Jayanta Bhaṭṭa, Nyāyamañjarī (c. 890 CE): apoha is circular — to
--   exclude the non-cow you must already grasp the cow.  Read that way the
--   pattern works only because the reader already holds the positive claim
--   it quotes, and a pattern that still matches after the surrounding
--   argument has changed underneath it is a match on nothing.
--
--   WHAT THEY WOULD SAY TO EACH OTHER ABOUT THIS MODULE.  The Naiyāyika
--   charge lands: this resolver can report Sthira for a pattern whose
--   meaning has drifted, and it does not detect that.  The Dignāgan reply
--   also lands: the alternative on offer — a line number — excludes
--   nothing at all and so is strictly worse, and a citation is not being
--   asked to carry meaning, only to be findable.  Neither refutes the
--   other here, and the module does not pick.  It decides byte occurrence,
--   which is decidable, and SAYS that it decides only that.  Synonymy is
--   left open, in the open form, as D1 of the standpoint store.
--
-- ────────────────────────────────────────────────────────────────────
-- THE LAW, learned by the doṣa-lekha lane three times in one session
-- (machine/dosa.lekha, records 0001 and 0006, whose `punarabhinaya` are a
-- count over a gitignored log and a guessed number; the later records
-- switched to `git show -s --format='%h %s' <hash>`):
--
--     A REPLAY MUST NAME A FIXED OBJECT.
--     Never a position.  Never a quantity the record is inside.
--     Never a HEAD-relative query.
--
-- Enforced here by the module boundary: `Nirdesha`'s constructors are NOT
-- exported.  The only ways in are the four smart constructors, each of
-- which returns `Either Calat Nirdesha`, and `parse`, which returns the
