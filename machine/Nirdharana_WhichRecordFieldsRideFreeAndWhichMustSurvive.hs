alphaTag :: Int -> String
alphaTag n
  | n <= 0    = ""
  | otherwise = alphaTag ((n - 1) `div` 26) ++ [toEnum (fromEnum 'A' + ((n - 1) `mod` 26))]

pad :: Int -> String -> String
pad n s = s ++ replicate (max 1 (n - length s)) ' '
