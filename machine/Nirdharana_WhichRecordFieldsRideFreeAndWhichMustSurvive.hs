-- Nirdharana_WhichRecordFieldsRideFreeAndWhichMustSurvive.hs
--
-- निर्धारण — "determination, ascertaining which of several it is".
--
-- ON THE NAME, AND WHAT IS NOT CLAIMED.  The compound is used here in the
-- sense the punarāgamana modules already use it: `निर्धारितम्` in
-- `punaragamana/src/Punaragamana/Sthanivadbhava_….agda` names the map whose
-- values a Carrier's base determines, and `पक्षः-न-निर्धारितः` /
-- `परिमाणम्-न-निर्धारितम्` / `शेषः-न-निर्धारितः` in
-- `punaragamana/src/Punaragamana/KuttakaValli_….agda` are the three theorems
-- that a slot is NOT so determined.  **No text and no date is claimed for the
-- term as a technical term of any school**, and none is asserted below.  It is
-- borrowed from those two modules and from nowhere else — the same declaration
-- `Punaragamana/Carrier.agda` makes about `punarāgamana` itself ("the compound
-- is chosen here, and no source is claimed for it").  The Āryabhaṭīya and the
-- Aṣṭādhyāyī citations that DO stand are in those modules' headers, at verse
-- and sūtra level, and they are not restated here as though this program had
-- opened either text.  It has not.
--
-- WHAT THIS PROGRAM IS.  A census of every `record … where` block with a
-- `field` section under `formal/cubical/` and `punaragamana/src/`, asking of
-- each one the punarāgamana question:
--
--     for a record R with fields x₁ … xₙ, is field xⱼ DETERMINED by the
--     others?  Equivalently: is the projection R → (the other fields) an
--     equivalence?  And in cubical Agda `isEquiv f` IS `∀ b → isContr
--     (fibre f b)`, so the question is not a judgement call — it is emitted
--     as a term and the kernel answers it.
--
-- The program parses, classifies, EMITS Agda modules into a scratch directory,
-- RUNS Agda on them, and prints a table.  It writes nothing into the corpus.
--
--   run:  runghc machine/Nirdharana_WhichRecordFieldsRideFreeAndWhichMustSurvive.hs
--   from the repository root.  Flags:
--       --no-check      parse and classify only; emit and run nothing
--       --limit N       run at most N probes (still parses everything)
--   The generated modules are always left in the scratch directory, whose path
--   the report prints, so a reader can open the exact term the kernel accepted.
--
-- THE CRITERION, one line, and it is what makes step 2 decisive rather than
-- heuristic: WHICH SIDE OF `f a ≡ b` IS BOUND.  Bind b and the fibre is
-- `singl (f a)` — contractible always, no h-level hypothesis, arbitrary A and
-- B — so the datum rides free.  Bind a and the fibre is the preimage, which is
-- arbitrary and is usually the SUBJECT of the module rather than a defect in
-- it.  A record FIELD of type `f (other fields) ≡ thisField` is bind-b.  A
-- record PARAMETER is bind-a.  The census keeps the two apart and reports the
-- bind-a records as level sets, not as failures.
--
-- AND THE FIBRE HAS THREE CASES, NOT TWO.  EMPTY (नष्टि), EXACTLY ONE (free),
-- MANY (a Carrier still exists, with the extra freedom recorded as data).
-- `isContr` merges EMPTY and MANY into one "no", and Saptabhangi.agda's
-- `दुर्नयः` proves any two-valued verdict on three seeds must identify two of
-- them.  So: GREEN is EXACTLY ONE; a separating pair is MANY; and EMPTY is a
-- case this instrument cannot certify at all, stated wherever a table would
-- otherwise imply it had been ruled out.
--
-- ─────────────────────────────────────────────────────────────────────────
-- WHAT IS MEASURED, AND THE LIMIT OF EACH MEASUREMENT, STATED AT THE SITE.
-- ─────────────────────────────────────────────────────────────────────────
--
--  1. लेखा · LEKHĀ, the census.  Every `record` head, its parameters, its
--     sort, its fields and their types.  Comments are stripped by a scanner
--     that tracks `{- -}` nesting and carves out `{-# … #-}` pragmas.
--
--     WHAT THE PARSER MISSES, stated because a census that hides its blind
--     spot is the exact defect this corpus exists to refuse:
--       · a record with NO `field` line at all (a record of no fields, or one
--         whose fields arrive by `open … public` from elsewhere) is counted as
--         a record and reported as fieldless — it is not silently dropped;
--       · fields written on the `field` line itself (`field  x : A`) ARE
--         parsed, but they are counted separately so the number is visible;
--       · a field declaration whose type continues on a line indented LESS
--         than the declaration is mis-joined.  Agda's layout forbids this, so
--         the case should be empty, and the count of unparsable declarations
--         is printed rather than assumed to be zero;
--       · implicit `{x : A}` and instance `⦃ x : A ⦄` fields are detected and
--         the record is excluded from probing, not silently mangled;
--       · a record inside a `where` block, or generated by a macro, or written
--         as an anonymous `record { … }` EXPRESSION, is not a declaration and
--         is not here;
--       · the field section is truncated at the first nested `record` /
--         `module` / `data` / `private` line, so a record declared inside
--         another record's field section loses nothing but is not merged.
--
--  2. वाहक-आकार · CARRIER-SHAPED, the cheap syntactic pass.  A field whose
--     type contains `≡` (or `PathP`) AND mentions another field of the same
--     record is a WITNESS field.  Its presence means the record is already
--     Carrier-shaped, and the split is readable off the witness's own type:
--     if that type is `L ≡ xⱼ` with `xⱼ` a field name not occurring in `L`,
--     then the determining map is `L`, the carried datum is `xⱼ`, and `xⱼ`
--     together with the witness ride free.
--     LIMIT: this is syntax.  It reports a SHAPE, never a verdict.  The
--     verdict is measurement 3.
--
--  3. प्रमाण · THE PROBE, which is the only thing here that is a verdict.
--     For each Carrier-shaped candidate the program writes a module
--
--         record CensusBase : Type where field ⟨the other fields⟩
--         censusFam : CensusBase → Type          -- the carried field's type
--         censusF   : (b : CensusBase) → censusFam b   -- the map L
--         reshuffle : Iso R (Σ[ b ∈ CensusBase ] singl (censusF b))
--             fun/inv by record reshuffling, BOTH round trips by `refl`
--         DETERMINED : R ≃ CensusBase
--         DETERMINED = compEquiv (isoToEquiv reshuffle)
--                        (Σ-contractSnd (λ b → isContrSingl (censusF b)))
--
--     and runs Agda on it.  GREEN is a machine-checked equivalence: the field
--     and its witness contribute zero degrees of freedom and everything
--     transports.  Nothing is constructed by hand; the only inputs are the
--     record's own field names and the witness's own type.
--
--     LIMIT, and it is the important one.  A RED here is THREE different
--     things and the program separates them, because collapsing them would
--     make the census worthless:
--       HOST-RED  the host module does not typecheck under THIS toolchain at
--                 all.  Several formal/cubical modules are written against
--                 agda/cubical v0.5 names (`solve`, `isSetRetract`, …) that
--                 v0.9 does not have.  That is a toolchain fact and NOT a
--                 mathematical verdict about the record.
--       ELAB-RED  the host checks but the generated module does not even
--                 elaborate — a name not in scope, a universe level the
--                 generator got wrong.  That is a defect in THIS PROGRAM and
--                 NOT a mathematical verdict either.
--       MATH-RED  host green, probe elaborates, and the equivalence or one of
--                 the two `refl`s fails.  Only this one says anything about
--                 the record — and even then it says "not determined BY THIS
--                 SPLIT, definitionally", not "not determined".
--
--  4. भेद · THE SEPARATING PAIR, the negative made equally mechanical.  For a
--     record with NO witness field the program emits two inhabitants agreeing
--     on every other field, differing on xⱼ, and a proof they are distinct —
--     exactly the output format of `पक्षः-न-निर्धारितः` and its two siblings
--     in `Punaragamana.KuttakaValli_…`, and of the three in
--     `Punaragamana.Sthanivadbhava_…`, which is what this automates.
--     LIMIT, stated flatly: this needs two provably distinct closed
--     inhabitants of xⱼ's type and one closed inhabitant of every other
--     field's type, and the program knows only ℕ (`0`/`1`, distinct by
--     `znots`) and `Bool` (`true`/`false`, distinct by `true≢false`).  Every
--     other record is reported as NOT ATTEMPTED, never as "determined".
--
--  ─────────────────────────────────────────────────────────────────────────
--  THE ONE THING THIS CENSUS CANNOT DO, SAID HERE SO THAT ITS ABSENCE FROM
--  THE TABLE IS NOT READ AS AN EMPTY RESULT.
--
--  A field that IS determined but carries NO witness cannot be found by
--  machine in general, and the reason is not laziness.  A GREEN verdict needs
--  the determining map `L`, and when a witness field is present that map is
--  written down in the witness's own type, which is why measurement 3 works.
--  With no witness field there is nowhere in the record to read `L` off from:
--  the record does not say what xⱼ is a function OF, so there is nothing to
--  emit.  Searching for such an `L` is proof search, not a census.
--
--  What the program CAN do, and does, is the nearest honest neighbour:
--    (a) MATH-RED and separating pairs — records where a field is provably
--        NOT determined, which is the negative half and is complete;
--    (b) वाहक-अनुक्त, "the carrier unsaid" — records that ARE Carrier-shaped,
--        confirmed GREEN by the kernel, whose own module never mentions
--        `Carrier`, `≃`, `Iso` or `ua` anywhere near them.  The equivalence is
--        true, checked, and unstated.  That is the actionable list this
--        program produces, and it is a strictly weaker statement than "a
--        determined field with no witness".  It is labelled as such below.
--
--  ─────────────────────────────────────────────────────────────────────────
--  TOOLCHAIN.  Agda 2.8.0, agda/cubical v0.9 (the pair Homebrew ships), from
--  ~/.agda/libraries.  `LC_ALL=C.utf8` is set by this program and is REQUIRED:
--  under a POSIX locale Agda crashes while printing its own error messages for
--  the Devanagari identifiers and replaces the diagnosis with advice about
--  code pages.  Probes are emitted with `--cubical --safe --guardedness`;
--  `--guardedness` is infective, so a probe without it cannot import the 411
--  corpus modules that have it.

