data Verdict = Green | MathRed | ElabRed | HostRed | NotRun String
  deriving (Eq)

instance Show Verdict where
  show Green      = "GREEN"
  show MathRed    = "RED (math)"
  show ElabRed    = "RED (elab — generator defect, NOT a verdict)"
  show HostRed    = "RED (host — toolchain, NOT a verdict)"
  show (NotRun s) = "not run: " ++ s

-- | An elaboration failure is a scope/level/import failure; a mathematical
--   failure is a type mismatch inside the assertions.  Anything that is
--   neither is reported as elab, which is the conservative side: it never
--   invents a mathematical verdict.
classifyErr :: String -> Verdict
classifyErr out
  | any (`isInfixOf` out) [ "Not in scope", "[Scope", "InfectiveImport"
                          , "[FileNotFound", "Ambiguous", "not a valid"
                          , "No such file", "duplicate", "Duplicate"
                          , "The name", "Set₁", "Setω", "level of the" ]
      = ElabRed
  | any (`isInfixOf` out) [ "!=", "Failed to solve", "does not have", "when checking" ]
      = MathRed
  | otherwise = ElabRed

