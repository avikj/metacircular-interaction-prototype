probeHeader :: String -> [String]
probeHeader nm =
  [ "{-# OPTIONS --cubical --safe --guardedness #-}"
  , "module " ++ nm ++ " where"
  , ""
  , "open import Cubical.Foundations.Prelude"
  , "open import Cubical.Foundations.Isomorphism"
  , "open import Cubical.Foundations.Equiv"
  , "open import Cubical.Data.Sigma"
  ]

-- | The Carrier probe.  Nothing below is a construction: every line is copied
--   from the record's own field names and the witness's own type.
emitP1 :: String -> Rec -> [(String, String)] -> (String, String, String, Orient) -> String
emitP1 nm r ps (wn, xj, lmap, orient) = unlines $
  probeHeader nm
  ++ [ "open import " ++ rModule r ]
  ++ rImports r
  ++ [ "" ]
  ++ modOpen
  ++ map ind
     ( [ "record CensusBase : Type where"
       , "  field"
       ]
    ++ [ "    " ++ n ++ " : " ++ ty | (n, ty, _) <- keep ]
    ++ [ ""
       , "censusFam : CensusBase → Type"
       , "censusFam censusB = " ++ letIn carriedTy
       , ""
       , "censusF : (censusB : CensusBase) → censusFam censusB"
       , "censusF censusB = " ++ letIn lmap
       , ""
       ]
    ++ singlDefs
    ++ [ "censusTo : " ++ rApp ++ " → censusΣ"
       , "censusTo censusR ="
       , "  record { " ++ intercalate " ; "
             [ n ++ " = " ++ rName r ++ "." ++ n ++ " censusR" | (n,_,_) <- keep ]
         ++ " } , ( " ++ rName r ++ "." ++ xj ++ " censusR"
         ++ " , " ++ rName r ++ "." ++ wn ++ " censusR )"
       , ""
       , "censusFrom : censusΣ → " ++ rApp
       , "censusFrom (censusB , (censusY , censusP)) ="
       , "  record { " ++ intercalate " ; "
             ( [ n ++ " = CensusBase." ++ n ++ " censusB" | (n,_,_) <- keep ]
            ++ [ xj ++ " = censusY", wn ++ " = censusP" ] )
         ++ " }"
       , ""
       , "censusReshuffle : Iso (" ++ rApp ++ ") censusΣ"
       , "Iso.fun      censusReshuffle = censusTo"
       , "Iso.inv      censusReshuffle = censusFrom"
       , "Iso.rightInv censusReshuffle _ = refl"
       , "Iso.leftInv  censusReshuffle _ = refl"
       , ""
       , "-- THE VERDICT.  Green here is the equivalence itself."
       , "DETERMINED : (" ++ rApp ++ ") ≃ CensusBase"
       , "DETERMINED = compEquiv (isoToEquiv censusReshuffle) censusContract"
       ] )
  where
    fs   = flatFields r
    keep = [ f | f@(n,_,_) <- fs, n /= xj, n /= wn ]
    -- `let`, NOT `where` and NOT `open CensusBase censusB`.  Both of those
    -- were tried and both fail on real corpus records: `open` makes the field
    -- name an AMBIGUOUS OVERLOADED PROJECTION against the host's own exported
    -- projection of the same name, and `where` is a module-level definition,
    -- so it is a ClashingDefinition against it.  A `let` is a local binding
    -- and simply shadows.  (VivekaPramana_TheRemainderIsLawfulAndTheNetBeats
    -- exhibits both, because it does `open विवेक-प्रमाण` at top level.)
    letIn body
      | null keep = body
      | otherwise =
          "let " ++ intercalate " ; "
            [ n ++ " = CensusBase." ++ n ++ " censusB" | (n,_,_) <- keep ]
          ++ " in " ++ body
    carriedTy = case [ ty | (n, ty, _) <- fs, n == xj ] of
                  (t:_) -> t
                  []    -> "Type"
    rApp = unwords (rName r : map fst ps)
    modOpen = if null ps then [] else
      [ "module _ " ++ unwords [ "(" ++ n ++ " : " ++ ty ++ ")" | (n, ty) <- ps ]
        ++ " where" ]
    ind s = if null ps then s else (if null s then s else "  " ++ s)
    singlDefs = case orient of
      Fwd ->
        [ "censusΣ : Type"
        , "censusΣ = Σ[ censusB ∈ CensusBase ] (Σ[ censusY ∈ censusFam censusB ] (censusF censusB ≡ censusY))"
        , ""
        , "censusContract : censusΣ ≃ CensusBase"
        , "censusContract = Σ-contractSnd (λ censusB → isContrSingl (censusF censusB))"
        , ""
        ]
      Rev ->
        [ "censusΣ : Type"
        , "censusΣ = Σ[ censusB ∈ CensusBase ] (Σ[ censusY ∈ censusFam censusB ] (censusY ≡ censusF censusB))"
        , ""
        , "-- the reversed singleton is contractible too; the term is written out"
        , "-- rather than imported because the cubical library ships only the"
        , "-- forward `isContrSingl`."
        , "censusRevContr : {A : Type} (a : A) → isContr (Σ[ y ∈ A ] (y ≡ a))"
        , "censusRevContr a = (a , refl) , λ (y , p) i → (p (~ i) , λ j → p (~ i ∨ j))"
        , ""
        , "censusContract : censusΣ ≃ CensusBase"
        , "censusContract = Σ-contractSnd (λ censusB → censusRevContr (censusF censusB))"
        , ""
        ]

-- | THE DESIGNED-FAILURE CONTROL, run against every GREEN.  A false green is
--   the worst outcome this program can produce, so each green is re-emitted
--   with the record's own witness replaced by `refl`, which asserts the
--   carried field is the map ON THE NOSE.  That mutant MUST fail.  If it
--   passes, the probe was proving nothing and the green is reported as
--   SUSPECT rather than as a verdict.
emitP1Control :: String -> Rec -> [(String, String)] -> (String, String, String, Orient) -> String
emitP1Control nm r ps s@(wn, _, _, _) =
  replaceAll (wn ++ " = censusP") (wn ++ " = refl") (emitP1 nm r ps s)

replaceAll :: String -> String -> String -> String
replaceAll from to = go
  where
    go [] = []
    go s@(c:cs) | from `isPrefixOf` s = to ++ go (drop (length from) s)
                | otherwise           = c : go cs

-- | The separating-pair probe: two inhabitants agreeing on every other field
--   and provably differing on xⱼ.  Only ℕ and Bool fields.
knownTwo :: String -> Maybe (String, String, String, String)
-- (default inhabitant, alternative, distinctness lemma, import)
knownTwo "ℕ"    = Just ("0", "1", "znots", "Cubical.Data.Nat")
knownTwo "Bool" = Just ("true", "false", "true≢false", "Cubical.Data.Bool")
knownTwo _      = Nothing

emitP3 :: String -> Rec -> String -> Maybe String
emitP3 nm r xj = do
  fs <- Just (flatFields r)
  (dflt0, alt, lemma, _) <- knownTwo =<< lookup3 xj fs
  dflts <- mapM (\(n, ty, _) -> do
                    (d, _, _, _) <- knownTwo ty
                    return (n, d)) fs
  let val n = fromMaybe "?" (lookup n dflts)
      recWith v = "record { " ++ intercalate " ; "
                    [ n ++ " = " ++ (if n == xj then v else val n)
                    | (n, _, _) <- fs ] ++ " }"
      others = [ n | (n, _, _) <- fs, n /= xj ]
  return $ unlines $
    [ "{-# OPTIONS --cubical --safe --guardedness #-}"
    , "module " ++ nm ++ " where"
    , ""
    , "open import Cubical.Foundations.Prelude"
    , "open import Cubical.Data.Nat"
    , "open import Cubical.Data.Bool"
    , "open import Cubical.Data.Empty"
    , "open import " ++ rModule r
    , ""
    , "censusR0 censusR1 : " ++ rName r
    , "censusR0 = " ++ recWith dflt0
    , "censusR1 = " ++ recWith alt
    , ""
    ]
    ++ concat [ [ "censusAgree-" ++ show i ++ " : " ++ rName r ++ "." ++ n
                    ++ " censusR0 ≡ " ++ rName r ++ "." ++ n ++ " censusR1"
                , "censusAgree-" ++ show i ++ " = refl", "" ]
              | (i, n) <- zip [(0::Int) ..] others ]
    ++ [ "-- THE VERDICT.  Green here means the field is NOT determined:"
       , "-- two inhabitants agree on every other field and are distinct."
       , "NOT-DETERMINED : censusR0 ≡ censusR1 → ⊥"
       , "NOT-DETERMINED censusP = " ++ lemma ++ " (cong "
           ++ rName r ++ "." ++ xj ++ " censusP)"
       ]
  where
    lookup3 k xs = case [ ty | (n, ty, _) <- xs, n == k ] of
      (t:_) -> Just t
      []    -> Nothing

