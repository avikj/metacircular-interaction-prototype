runAgda :: FilePath -> IO (ExitCode, String)
runAgda f = do
  let args = concat [ ["-i", d] | d <- scratchDir : incdirs ] ++ [f]
      cp = (proc "agda" args) { env = Just [("LC_ALL", "C.utf8"), ("PATH", "/opt/homebrew/bin:/usr/bin:/bin:/usr/local/bin"), ("HOME", "/Users/avikjain")] }
  r <- try (readCreateProcessWithExitCode cp "")
  case r of
    Left e -> return (ExitFailure 99, "spawn failed: " ++ show (e :: SomeException))
    Right (c, o, e) -> return (c, o ++ e)

