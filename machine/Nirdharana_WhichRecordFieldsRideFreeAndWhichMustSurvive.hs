-- ============================================================ filesystem

walk :: [String] -> FilePath -> IO [FilePath]
walk skips root = do
  isDir <- doesDirectoryExist root
  if not isDir
    then return [root]
    else do
      names <- listDirectory root
      fmap concat . forM (sort names) $ \n ->
        if n `elem` skips || "." `isPrefixOf` n
          then return []
          else walk skips (root </> n)

readFileSafe :: FilePath -> IO String
readFileSafe p = do
  r <- try (do s <- readFile p; length s `seq` return s)
  case r of
    Left e  -> let _ = (e :: SomeException) in return ""
    Right s -> return s

-- ============================================================ comment scan

-- | Blank out comments, line by line, carrying `{- -}` nesting depth across
--   lines.  `{-# … #-}` is a pragma, not a comment, and is left alone.  The
--   output has the same number of lines and the same column positions, so
--   indentation is preserved exactly.
decomment :: [String] -> [String]
decomment = go (0 :: Int)
  where
    go _ [] = []
    go d (l:ls) = let (l', d') = one d l in l' : go d' ls
    one d [] = ([], d)
    one d s@(c:cs)
      | d == 0, "{-#" `isPrefixOf` s = keepPragma d s
      | d == 0, "--" `isPrefixOf` s, notOperator s = (map blank s, d)
      | "{-" `isPrefixOf` s = let (r, d') = one (d + 1) (drop 2 s)
                              in ("  " ++ r, d')
      | "-}" `isPrefixOf` s, d > 0 = let (r, d') = one (d - 1) (drop 2 s)
                                     in ("  " ++ r, d')
      | d > 0 = let (r, d') = one d cs in (blank c : r, d')
      | otherwise = let (r, d') = one d cs in (c : r, d')
    keepPragma d s = case breakOn "#-}" s of
      Nothing        -> (s, d)
      Just (a, rest) -> let (r, d') = one d rest in (a ++ "#-}" ++ r, d')
    blank c = if isSpace c then c else ' '
    -- `--` only starts a comment when it is not glued into a longer operator
    -- token (Agda: `--` must be followed by a non-name character).
    notOperator s = case drop 2 s of
      []      -> True
      (c : _) -> not (c `elem` "-!#$%&*+./<=>?@\\^|~:")

breakOn :: String -> String -> Maybe (String, String)
breakOn pat = go ""
  where
    go _ [] = Nothing
    go acc s@(c:cs)
      | pat `isPrefixOf` s = Just (reverse acc, drop (length pat) s)
      | otherwise          = go (c : acc) cs

-- ============================================================ record model

data Field = Field
  { fNames  :: [String]
  , fType   :: String
  , fHidden :: Bool
  } deriving (Show)

data Rec = Rec
  { rFile     :: FilePath
  , rModule   :: String
  , rName     :: String
  , rLine     :: Int
  , rIndent   :: Int
  , rParams   :: String
  , rSort     :: String
  , rFields   :: [Field]
  , rBadDecls :: Int          -- ^ field declarations the parser could not split
  , rInline   :: Bool         -- ^ some fields were on the `field` line itself
  , rHasField :: Bool
  , rCoind    :: Bool
  , rNoEta    :: Bool
  , rBody     :: [String]
  , rImports  :: [String]   -- ^ the host module's own top-level import lines
  }

flatFields :: Rec -> [(String, String, Bool)]
flatFields r = [ (n, fType f, fHidden f) | f <- rFields r, n <- fNames f ]

fieldNames :: Rec -> [String]
fieldNames = map (\(n,_,_) -> n) . flatFields

indentOf :: String -> Int
indentOf = length . takeWhile (== ' ')

blankLine :: String -> Bool
blankLine = all isSpace

collapse :: String -> String
collapse = unwords . words

trim :: String -> String
trim = dropWhile isSpace . reverse . dropWhile isSpace . reverse

-- | Split at the first occurrence of a token at bracket depth 0.
splitTop :: String -> String -> Maybe (String, String)
splitTop tok = go (0 :: Int) ""
  where
    go _ _ [] = Nothing
    go d acc s@(c:cs)
      | d == 0, tok `isPrefixOf` s = Just (reverse acc, drop (length tok) s)
      | c `elem` "([{" || c == '⦃' = go (d + 1) (c : acc) cs
      | c `elem` ")]}" || c == '⦄' = go (d - 1) (c : acc) cs
      | otherwise                  = go d (c : acc) cs

countTop :: String -> String -> Int
countTop tok s = case splitTop tok s of
  Nothing      -> 0
  Just (_, r)  -> 1 + countTop tok r

tokensOf :: String -> [String]
tokensOf = words . map sep
  where sep c = if c `elem` "()[]{},;⦃⦄" then ' ' else c

mentionsTok :: String -> String -> Bool
mentionsTok n ty = n `elem` tokensOf ty

-- ============================================================ the parser

parseFile :: FilePath -> String -> (Maybe String, [Rec])
parseFile path src =
  let ls   = decomment (lines src)
      modn = case [ w | l <- ls, "module " `isPrefixOf` l
                      , w <- take 1 (drop 1 (words l)) ] of
               (n:_) -> Just n
               []    -> Nothing
      idx  = zip [1 ..] ls
      -- A host's `open import M` does NOT re-export M's names, so a probe that
      -- imports only the host cannot see `ℕ`.  The host's own import lines are
      -- carried into the probe verbatim.  (Found by the first run: every P1
      -- probe died with `Not in scope: ℕ`.)
      imps = gatherOpens ls
      recs = mapMaybe (uncurry (tryRecord ls imps (fromMaybe "?" modn) path)) idx
  in (modn, recs)

-- | Every column-0 `import` / `open import` / `open …` line of the host,
--   with `using (…)` clauses that spill onto following indented lines joined
--   back on.  `open CommRingStr (ℤCommRing .snd)` in Swarm.S09SmithKuttaka is
--   why plain `import` lines are not enough: the record's field types use `·`,
--   which reaches scope through that `open` and through nothing else.
gatherOpens :: [String] -> [String]
gatherOpens = go
  where
    go [] = []
    go (l:ls)
      | indentOf l == 0, isOpen l =
          let (cont, rest) = span (\x -> not (blankLine x) && indentOf x > 0) ls
          in collapse (unwords (l : cont)) : go rest
      | otherwise = go ls
    isOpen l = case words l of
      ("import" : _) -> True
      ("open" : _)   -> True
      _              -> False

tryRecord :: [String] -> [String] -> String -> FilePath -> Int -> String -> Maybe Rec
tryRecord ls imps modn path n l
  | ("record" : _) <- words l
  , let ind = indentOf l
  = do (hdr, hdrEnd) <- gatherHeader ls n ind
       let afterRec = trim (drop (length "record") (dropWhile (== ' ') hdr))
       (nm, rest0) <- nameAndRest afterRec
       let (params, sortStr) = case splitTop ":" rest0 of
             Just (p, s) -> (trim p, trim (dropWhereTail s))
             Nothing     -> (trim (dropWhereTail rest0), "")
           body = takeBody ind (drop hdrEnd ls)
           (fs, bad, inl, hadField) = parseFields body
       Just Rec { rFile = path, rModule = modn, rName = nm, rLine = n
                , rIndent = ind, rParams = params, rSort = sortStr
                , rFields = fs, rBadDecls = bad, rInline = inl
                , rHasField = hadField
                , rCoind = any (("coinductive" ==) . firstWord) body
                , rNoEta = any (("no-eta-equality" ==) . firstWord) body
                , rBody = body, rImports = imps }
  | otherwise = Nothing
  where
    firstWord s = case words s of { (w:_) -> w ; [] -> "" }
    dropWhereTail s =
      let ws = words s
      in if not (null ws) && last ws == "where"
           then unwords (init ws) else unwords ws
    nameAndRest s = case words s of
      (w:_) | w /= ":" -> Just (w, trim (drop (length w) (dropWhile (==' ') s)))
      _                -> Nothing

-- | Join the record head across lines until a `where` token is seen.
--   Returns the joined header and how many lines from `n` it consumed.
gatherHeader :: [String] -> Int -> Int -> Maybe (String, Int)
gatherHeader ls n ind = go 0 ""
  where
    go k acc
      | k > 6 = Nothing
      | otherwise = case drop (n - 1 + k) ls of
          [] -> Nothing
          (x:_) ->
            let acc' = if null acc then x else acc ++ " " ++ trim x
            in if "where" `elem` words x
                 then Just (acc', n + k)
                 else if k > 0 && not (blankLine x) && indentOf x <= ind
                        then Nothing
                        else go (k + 1) acc'

takeBody :: Int -> [String] -> [String]
takeBody ind = takeWhile (\x -> blankLine x || indentOf x > ind)

-- | Fields.  Returns (fields, unparsable declarations, inline?, saw a `field`?)
parseFields :: [String] -> ([Field], Int, Bool, Bool)
parseFields = outside
  where
    outside [] = ([], 0, False, False)
    outside (l:ls)
      | ("field" : rest) <- words l =
          let fInd  = indentOf l
              inlin = not (null rest)
              inlF  = if inlin then maybe [] (: []) (mkField (unwords rest))
                               else []
              inlBad = if inlin && null inlF then 1 else 0
              (fs, bad, ls') = inside fInd Nothing [] ls
              (fs2, bad2, _, _) = outside ls'
          in (inlF ++ fs ++ fs2, inlBad + bad + bad2, inlin, True)
      | otherwise = let (a, b, c, d) = outside ls in (a, b, c, d)

    stopper l = case words l of
      (w:_) -> w `elem` ["record","module","data","private","postulate"
                        ,"open","import","field","constructor","coinductive"
                        ,"inductive","no-eta-equality","eta-equality"]
      []    -> False

    inside _ _ acc [] = (finish acc, badOf acc, [])
    inside fInd declInd acc (l:ls)
      | blankLine l = inside fInd declInd acc ls
      | indentOf l <= fInd = (finish acc, badOf acc, l : ls)
      | stopper l = (finish acc, badOf acc, l : ls)
      | otherwise =
          case declInd of
            Nothing -> inside fInd (Just (indentOf l)) [trim l] ls
            Just d
              | indentOf l == d  -> inside fInd declInd (trim l : acc) ls
              | indentOf l >  d  ->
                  case acc of
                    (a:as) -> inside fInd declInd ((a ++ " " ++ trim l) : as) ls
                    []     -> inside fInd declInd [trim l] ls
              | otherwise -> (finish acc, badOf acc, l : ls)

    finish = mapMaybe mkField . reverse
    badOf  = length . filter (not . isJust . mkField) . reverse

    mkField s0 =
      let s = collapse s0 in
      case splitTop ":" s of
        Nothing -> Nothing
        Just (lhs, rhs)
          | null (words lhs) || null (words rhs) -> Nothing
          | otherwise ->
              let hidden = any (`elem` "{⦃") lhs
                  nms = words (map (\c -> if c `elem` "{}⦃⦄" then ' ' else c) lhs)
              in if null nms then Nothing
                 else Just (Field nms (collapse rhs) hidden)

-- ============================================================ classification

-- | A witness field: a path type mentioning another field of the same record.
isWitness :: Rec -> (String, String, Bool) -> Bool
isWitness r (n, ty, _) =
  (("≡" `isInfixOf` ty) || ("PathP" `isInfixOf` ty))
  && any (\m -> m /= n && mentionsTok m ty) (fieldNames r)

data Orient = Fwd | Rev deriving (Eq, Show)

-- | The Carrier split read off a witness's own type: `L ≡ xⱼ` (Fwd) or
--   `xⱼ ≡ L` (Rev), with `xⱼ` a field of the record not occurring in `L`.
carrierSplit :: Rec -> (String, String, Bool) -> Maybe (String, String, String, Orient)
carrierSplit r (wn, ty, _)
  -- The split is only meaningful when the whole type IS a path.  A `¬`, a
  -- top-level `→`, or a binder means the `≡` sits under something else, and
  -- `¬ x₀ ≡ y₀` read as a Carrier split is exactly the false positive this
  -- guard was added to kill (AchromaticToy.Stage, first run).
  | "¬" `isInfixOf` ty = Nothing
  | isJust (splitTop "→" ty) = Nothing
  | any (`isInfixOf` ty) ["∀", "λ", "Σ[", "Π"] = Nothing
  | countTop "≡" ty /= 1 = Nothing
  | otherwise = case splitTop "≡" ty of
      Nothing -> Nothing
      Just (lhs, rhs) ->
        let l = trim lhs; rr = trim rhs; fns = fieldNames r
            -- A remaining field whose own type mentions xⱼ blocks the split:
            -- dropping xⱼ from the base would leave that field's type
            -- ill-formed, and repairing it by substituting L makes the round
            -- trip hold only up to transport, not by refl.  Reported, not
            -- silently attempted.  (BornDistribution₂.positive : Positive
            -- denominator is the corpus's instance.)
            dependents x = [ n | (n, t, _) <- flatFields r
                               , n /= x, n /= wn, mentionsTok x t ]
        in if rr `elem` fns && rr /= wn && not (mentionsTok rr l)
                && null (dependents rr)
             then Just (wn, rr, l, Fwd)
             else if l `elem` fns && l /= wn && not (mentionsTok l rr)
                     && null (dependents l)
                    then Just (wn, l, rr, Rev)
                    else Nothing

-- ============================================================ probe eligibility

data Skip = Skip { skWhy :: String } deriving (Show)

goodSorts :: [String]
goodSorts = ["Type", "Type₀", "Type0", "Set", "Set₀", "Type ℓ-zero"]

-- | Parameters: only fully explicit `(names : type)` groups are supported,
--   because the probe has to re-apply them by name.
paramGroups :: String -> Maybe [(String, String)]
paramGroups s0
  | null (trim s0) = Just []
  | any (`elem` "{⦃") s0 = Nothing
  | otherwise = go (trim s0)
  where
    go [] = Just []
    go ('(':rest) = case splitClose 0 "" rest of
      Nothing -> Nothing
      Just (inside, after) -> case splitTop ":" inside of
        Nothing -> Nothing
        Just (ns, ty) -> ((map (\n -> (n, collapse ty)) (words ns)) ++) <$> go (trim after)
    go _ = Nothing
    splitClose _ _ [] = Nothing
    splitClose d acc (c:cs)
      | c == ')' && d == 0 = Just (reverse acc, cs)
      | c == ')'           = splitClose (d - 1) (c : acc) cs
      | c == '('           = splitClose (d + 1) (c : acc) cs
      | otherwise          = splitClose d (c : acc) cs

eligible :: Rec -> Either Skip [(String, String)]
eligible r
  | rIndent r /= 0            = Left (Skip "nested (not a top-level record)")
  | not (rHasField r)         = Left (Skip "no field section")
  | rCoind r                  = Left (Skip "coinductive")
  | rNoEta r                  = Left (Skip "no-eta-equality")
  | any (\(_,_,h) -> h) (flatFields r) = Left (Skip "implicit/instance field")
  | rBadDecls r > 0           = Left (Skip "unparsable field declaration")
  | rSort r `notElem` goodSorts = Left (Skip ("sort not Type: " ++ rSort r))
  | otherwise = case paramGroups (rParams r) of
      Nothing -> Left (Skip ("parameters not plain explicit: " ++ rParams r))
      Just ps -> Right ps

