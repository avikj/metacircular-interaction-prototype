"""Exact geometric optics: rational media, piecewise-linear rays, and an
optical path length that is compared **exactly** and never approximated.

The obstacle, and how it is removed
-----------------------------------
An optical path length is a sum of terms ``n * sqrt(dx^2 + dy^2)``.  With
rational ``n`` and rational coordinates each term is a rational multiple of the
square root of a rational, so an optical path length lives in the field
``Q(sqrt p_1, ..., sqrt p_r)`` for finitely many primes.  Every such number has
an exact canonical form

    sum_i  a_i * sqrt(m_i)        a_i in Q,  m_i distinct squarefree positive ints

and that form is the ``Surd`` class below.  Two facts make comparison exact and
*total*:

* **Zero is decidable syntactically.**  Square roots of distinct squarefree
  positive integers are linearly independent over ``Q`` (Besicovitch 1940).  So
  a canonical ``Surd`` is zero iff every coefficient is zero -- a finite check
  on ``Fraction``s, no arithmetic on irrationals at all.
* **Nonzero is decidable by rational bracketing.**  If some coefficient is
  nonzero the value is a nonzero real, and enclosing each ``sqrt(m)`` in a
  rational interval of width ``2^-k`` (obtained from an *integer* square root of
  ``m * 4^k``) gives a rational interval around the sum that shrinks to nothing.
  Refine ``k`` until the interval excludes 0.  It always does, because we have
  already established the value is not 0.

So ``Surd.sign()`` is exact, total, deterministic, and never constructs a float.
The two-term case is decided by the primitive the brief names -- compare
``a*sqrt(x)`` against ``b*sqrt(y)`` by comparing ``a^2 x`` against ``b^2 y``,
signs handled first -- and that primitive is exported as
``compare_scaled_sqrt`` and tested directly.

What is here
------------
``Surd``               exact sums of rational multiples of square roots
``Vec``                a point with exact rational coordinates
``Medium``             a named region with an exact rational refractive index
``Ray``                a piecewise-linear path plus the medium of each segment
``optical_path_length``exact OPL of a ``Ray``, as a ``Surd``
``InterfaceStack``     the discrete path family: parallel interfaces, a rational
                       lattice of crossing points on each, and the OPL of any
                       choice of crossings
``MirrorArc``          a discrete family of reflection points on a circle,
                       generated by the rational chart (CRYSTAL.md Sec.4)
``snell_residual``     ``n1 sin t1 - n2 sin t2`` as an exact ``Surd``
``reflection_residual``the law of reflection as an exact ``Surd``
``critical_points``    stationary points of a discrete family, by exact sign
                       changes of the first difference -- *not* an optimizer

Nothing in this module knows Snell's law.  ``snell_residual`` is a
*measurement* applied to a route after it is found; no search function calls it,
and ``tests/test_physics.py`` asserts that by walking this file's AST.
"""

