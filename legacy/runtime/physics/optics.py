@dataclass(frozen=True)
class Vec:
    """A point with exact rational coordinates."""

    x: Fraction
    y: Fraction

    @staticmethod
    def of(x, y) -> "Vec":
        return Vec(exact(x), exact(y))

    def minus(self, other: "Vec") -> "Vec":
        return Vec(self.x - other.x, self.y - other.y)

    def norm2(self) -> Fraction:
        """The exact squared length.  The unsquared length is generally a Surd."""
        return self.x * self.x + self.y * self.y

    def norm(self) -> Surd:
        return Surd.sqrt(self.norm2())

    def width(self) -> int:
        """Exact-arithmetic width: bits in the numerators and denominators."""
        out = 0
        for v in (self.x, self.y):
            out += abs(v.numerator).bit_length() + v.denominator.bit_length()
        return out

    def render(self) -> str:
        def f(v: Fraction) -> str:
            return str(v.numerator) if v.denominator == 1 else "%d:%d" % (
                v.numerator, v.denominator)
        return "(%s, %s)" % (f(self.x), f(self.y))


@dataclass(frozen=True)
class Medium:
    """A named optical medium with an exact rational refractive index ``n > 0``.

    ``n`` is rational on purpose.  Every index used in this package is a ratio
    of small integers, so every optical path length stays inside
    ``Q(sqrt ...)`` and every comparison stays exact.  A "physical" index like
    1.5168 is a decimal, i.e. a rational, and is representable here as
    ``Fraction(1897, 1250)`` with no loss whatsoever.
    """

    name: str
    index: Fraction

    @staticmethod
    def of(name: str, index) -> "Medium":
        n = exact(index)
        if n <= 0:
            raise OpticsError("a refractive index must be positive: %s" % n)
        return Medium(name, n)

    def render(self) -> str:
        n = self.index
        return "%s(n=%s)" % (self.name, str(n.numerator) if n.denominator == 1
                             else "%d:%d" % (n.numerator, n.denominator))


@dataclass(frozen=True)
class Ray:
    """A piecewise-linear path: ``k+1`` points and the medium of each of ``k``
    segments.  Nothing here asserts the path is physical; that is what the
    optimizer and the stationarity analysis are for."""

    points: Tuple[Vec, ...]
    media: Tuple[Medium, ...]

    def __post_init__(self) -> None:
        if len(self.points) < 2:
            raise OpticsError("a ray needs at least two points")
        if len(self.media) != len(self.points) - 1:
            raise OpticsError("each segment needs exactly one medium")

    def segments(self) -> Iterable[Tuple[Medium, Vec, Vec]]:
        for i, m in enumerate(self.media):
            yield (m, self.points[i], self.points[i + 1])

    def width(self) -> int:
        return sum(p.width() for p in self.points)

    def render(self) -> str:
        return " -> ".join(p.render() for p in self.points)


def optical_path_length(ray: Ray) -> Surd:
    """``sum_segments n * |p_{i+1} - p_i|``, exact, as a ``Surd``."""
    total = Surd.zero()
    for medium, p, q in ray.segments():
        COUNTERS.bump("optics.segment")
        total = total + Surd.scaled_sqrt(medium.index, q.minus(p).norm2())
    COUNTERS.bump("optics.opl")
    return total


def optical_time(ray: Ray, c: Quantity) -> Tuple[Surd, D.Dimension]:
    """OPL divided by the speed of light: the *time* Fermat's principle is about.

    Returned as ``(surd, dimension)`` because a ``Quantity`` holds a rational
    magnitude and an OPL is generally irrational.  The dimension is computed by
    ``dimension.py``, so ``optical_time`` of a path measured in metres against a
    ``c`` in metres per second has dimension ``T`` and could not have any other.
    """
    if c.value <= 0:
        raise OpticsError("the speed of light must be a positive magnitude")
    reciprocal = Fraction(c.value.denominator, c.value.numerator)
    return (optical_path_length(ray).scale(reciprocal), LENGTH.over(c.dim))


