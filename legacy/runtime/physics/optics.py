def reset_caches() -> None:
    """Drop every memo table in this module.

    The memo tables are pure optimisations -- they change how many counter
    bumps a computation costs and nothing about its answer.  Demos call this
    first so their counter dumps are reproducible from a cold cache rather than
    depending on what ran earlier in the same process.
    """
    _SQUAREFREE.clear()
    _BRACKET.clear()
    _SIGN.clear()


def integer_sqrt(n: int) -> int:
    """``floor(sqrt(n))`` by Newton's method on integers.  Exact, no ``math``."""
    if isinstance(n, bool) or not isinstance(n, int):
        raise OpticsError("integer_sqrt needs an int, got %r" % (n,))
    if n < 0:
        raise OpticsError("integer_sqrt of a negative integer")
    if n < 2:
        return n
    COUNTERS.bump("surd.isqrt")
    x = 1 << ((n.bit_length() + 1) // 2)
    while True:
        y = (x + n // x) // 2
        if y >= x:
            return x
        x = y


def is_perfect_square(n: int) -> bool:
    if n < 0:
        return False
    r = integer_sqrt(n)
    return r * r == n


_SQUAREFREE: Dict[int, Tuple[int, int]] = {}


def squarefree_part(n: int) -> Tuple[int, int]:
    """``n = s^2 * f`` with ``f`` squarefree; returns ``(s, f)``.  ``n >= 0``."""
    if n < 0:
        raise OpticsError("squarefree_part of a negative integer")
    if n == 0:
        return (0, 1)
    got = _SQUAREFREE.get(n)
    if got is not None:
        return got
    COUNTERS.bump("surd.factor")
    s, m = 1, n
    d = 2
    while d * d <= m:
        if m % d == 0:
            e = 0
            while m % d == 0:
                m = m // d
                e += 1
            s *= d ** (e // 2)
        d += 1 if d == 2 else 2
    f = n // (s * s)
    _SQUAREFREE[n] = (s, f)
    return (s, f)


def _sqrt_of_fraction(q: Fraction) -> Tuple[Fraction, int]:
    """``sqrt(q) = c * sqrt(m)`` with ``c`` rational and ``m`` squarefree int.

    ``sqrt(p/d) = sqrt(p*d)/d``, then pull the square part out of ``p*d``.
    """
    if q < 0:
        raise OpticsError("sqrt of a negative rational is not a real length")
    if q == 0:
        return (Fraction(0), 1)
    p, d = q.numerator, q.denominator
    s, f = squarefree_part(p * d)
    return (Fraction(s, d), f)


# --------------------------------------------------------------------------
# the primitive the brief names: a*sqrt(x)  vs  b*sqrt(y), exactly
# --------------------------------------------------------------------------

def compare_scaled_sqrt(a, x, b, y) -> int:
    """Compare ``a*sqrt(x)`` with ``b*sqrt(y)``; ``-1``, ``0`` or ``1``.

    ``a, b`` exact rationals of any sign; ``x, y`` exact nonnegative rationals.
    Signs are resolved first, then the magnitudes by comparing ``a^2 x`` with
    ``b^2 y`` -- squaring is monotone on nonnegatives, so this is exact and no
    square root is ever evaluated.
    """
    a, b = exact(a), exact(b)
    x, y = exact(x), exact(y)
    if x < 0 or y < 0:
        raise OpticsError("compare_scaled_sqrt needs nonnegative radicands")
    COUNTERS.bump("surd.compare_scaled")
    sa = 0 if (a == 0 or x == 0) else (1 if a > 0 else -1)
    sb = 0 if (b == 0 or y == 0) else (1 if b > 0 else -1)
    if sa != sb:
        return 1 if sa > sb else -1
    if sa == 0:
        return 0
    lhs = a * a * x
    rhs = b * b * y
    if lhs == rhs:
        return 0
    bigger = 1 if lhs > rhs else -1
    return bigger if sa > 0 else -bigger


# --------------------------------------------------------------------------
# Surd: exact sums of rational multiples of square roots
# --------------------------------------------------------------------------

_BRACKET: Dict[Tuple[int, int], Tuple[Fraction, Fraction]] = {}
_SIGN: Dict[Tuple[Tuple[int, Fraction], ...], int] = {}

MAX_BRACKET_BITS = 8192


def _bracket(m: int, k: int) -> Tuple[Fraction, Fraction]:
    """Rationals ``lo <= sqrt(m) <= hi`` with ``hi - lo <= 2^-k``."""
    if m == 1:
        return (Fraction(1), Fraction(1))
    key = (m, k)
    got = _BRACKET.get(key)
    if got is not None:
        return got
    scale = 1 << k
    s = integer_sqrt(m * scale * scale)
    out = (Fraction(s, scale), Fraction(s + 1, scale))
    _BRACKET[key] = out
    return out


@dataclass(frozen=True)
class Surd:
    """``sum_i a_i sqrt(m_i)``: coefficients exact, radicands squarefree ints.

    Canonical by construction -- radicands are distinct, sorted ascending, and
    zero coefficients are dropped -- so ``Surd`` equality *is* mathematical
    equality (Besicovitch), and ``terms == ()`` is exactly the number zero.
    """

    terms: Tuple[Tuple[int, Fraction], ...]

    # -- constructors ----------------------------------------------------
    @staticmethod
    def zero() -> "Surd":
        return Surd(())

    @staticmethod
    def rational(q) -> "Surd":
        q = exact(q)
        return Surd(() if q == 0 else ((1, q),))

    @staticmethod
    def scaled_sqrt(c, q) -> "Surd":
        """``c * sqrt(q)`` for exact rational ``c`` and nonnegative rational ``q``."""
        c = exact(c)
        q = exact(q)
        if c == 0 or q == 0:
            return Surd(())
        f, m = _sqrt_of_fraction(q)
        return Surd(((m, c * f),))

    @staticmethod
    def sqrt(q) -> "Surd":
        return Surd.scaled_sqrt(1, q)

    @staticmethod
    def _canon(d: Dict[int, Fraction]) -> "Surd":
        return Surd(tuple(sorted((m, c) for m, c in d.items() if c != 0)))

    # -- arithmetic ------------------------------------------------------
    @staticmethod
    def _coerce(x) -> "Surd":
        """Accept an exact rational where a ``Surd`` is expected, and nothing else.

        This is what lets ``execute.extract.scalarize`` -- which computes
        ``sum(w * c for ...)`` over a cost vector with integer weights, starting
        from the integer ``0`` -- run over an optical cost vector unmodified.
        A float still raises, through ``dimension.exact``.
        """
        if isinstance(x, Surd):
            return x
        return Surd.rational(x)

    def __add__(self, other) -> "Surd":
        other = Surd._coerce(other)
        COUNTERS.bump("surd.add")
        d: Dict[int, Fraction] = dict(self.terms)
        for m, c in other.terms:
            d[m] = d.get(m, Fraction(0)) + c
        return Surd._canon(d)

    def __neg__(self) -> "Surd":
        return Surd(tuple((m, -c) for m, c in self.terms))

    def __radd__(self, other) -> "Surd":
        return Surd._coerce(other) + self

    def __sub__(self, other) -> "Surd":
        return self + (-Surd._coerce(other))

    def __rsub__(self, other) -> "Surd":
        return Surd._coerce(other) + (-self)

    def scale(self, k) -> "Surd":
        """Multiply by an exact rational."""
        k = exact(k)
        if k == 0:
            return Surd(())
        COUNTERS.bump("surd.scale")
        return Surd(tuple((m, c * k) for m, c in self.terms))

    def __rmul__(self, other) -> "Surd":
        return self.scale(other)

    def __mul__(self, other) -> "Surd":
        if not isinstance(other, Surd):
            return self.scale(other)
        COUNTERS.bump("surd.mul")
        d: Dict[int, Fraction] = {}
        for m1, c1 in self.terms:
            for m2, c2 in other.terms:
                s, f = squarefree_part(m1 * m2)
                d[f] = d.get(f, Fraction(0)) + c1 * c2 * s
        return Surd._canon(d)

    # -- exact decision --------------------------------------------------
    def as_fraction(self) -> Optional[Fraction]:
        """The exact rational value, or ``None`` if the number is irrational."""
        if not self.terms:
            return Fraction(0)
        if len(self.terms) == 1 and self.terms[0][0] == 1:
            return self.terms[0][1]
        return None

    def is_zero(self) -> bool:
        """Exact, and *syntactic*: distinct square roots are independent over Q."""
        return not self.terms

    def sign(self) -> int:
        """``-1``, ``0`` or ``1``.  Exact and total; never approximate."""
        if not self.terms:
            return 0
        got = _SIGN.get(self.terms)
        if got is not None:
            COUNTERS.bump("surd.sign_hit")
            return got
        COUNTERS.bump("surd.sign")
        if len(self.terms) == 1:
            m, c = self.terms[0]
            out = 1 if c > 0 else -1
        elif len(self.terms) == 2:
            (m1, c1), (m2, c2) = self.terms
            # sign(c1 sqrt m1 + c2 sqrt m2) = compare(c1 sqrt m1, -c2 sqrt m2)
            out = compare_scaled_sqrt(c1, m1, -c2, m2)
        else:
            out = self._sign_by_bracket()
        _SIGN[self.terms] = out
        return out

    def _sign_by_bracket(self) -> int:
        k = 16
        while k <= MAX_BRACKET_BITS:
            COUNTERS.bump("surd.refine")
            lo = Fraction(0)
            hi = Fraction(0)
            for m, c in self.terms:
                bl, bh = _bracket(m, k)
                if c > 0:
                    lo += c * bl
                    hi += c * bh
                else:
                    lo += c * bh
                    hi += c * bl
            if lo > 0:
                return 1
            if hi < 0:
                return -1
            k *= 2
        raise OpticsError(                                # pragma: no cover
            "sign undecided at 2^-%d; a nonzero canonical Surd must resolve, so "
            "this is a bug, not a bound" % MAX_BRACKET_BITS)

    def compare(self, other) -> int:
        COUNTERS.bump("surd.compare")
        return (self - Surd._coerce(other)).sign()

    # -- ordering (this is what makes L3's Pareto machinery apply verbatim) --
    def __eq__(self, other) -> bool:
        if not isinstance(other, Surd):
            return NotImplemented
        return self.terms == other.terms

    def __hash__(self) -> int:
        return hash(self.terms)

    def __lt__(self, other) -> bool:
        return self.compare(other) < 0

    def __le__(self, other) -> bool:
        return self.compare(other) <= 0

    def __gt__(self, other) -> bool:
        return self.compare(other) > 0

    def __ge__(self, other) -> bool:
        return self.compare(other) >= 0

    # -- views ------------------------------------------------------------
    def bracket(self, k: int = 32) -> Tuple[Fraction, Fraction]:
        """An exact rational enclosure, for printing.  No float is produced."""
        lo = Fraction(0)
        hi = Fraction(0)
        for m, c in self.terms:
            bl, bh = _bracket(m, k)
            if c > 0:
                lo += c * bl
                hi += c * bh
            else:
                lo += c * bh
                hi += c * bl
        return (lo, hi)

    def render(self) -> str:
        if not self.terms:
            return "0"
        parts = []
        for m, c in self.terms:
            cs = str(c.numerator) if c.denominator == 1 else "%d:%d" % (c.numerator,
                                                                       c.denominator)
            parts.append(cs if m == 1 else "%s*sqrt(%d)" % (cs, m))
        return " + ".join(parts).replace("+ -", "- ")

    def render_approx(self, digits: int = 6) -> str:
        """A decimal *string* built from exact integer arithmetic, for reading.

        No float is constructed: the digits come from an integer division of the
        exact rational bracket's midpoint numerator.  It is a rendering, and no
        decision anywhere in this package is made from it.
        """
        lo, hi = self.bracket(64)
        mid2 = lo + hi
        scale = 10 ** digits
        n = (mid2.numerator * scale) // (mid2.denominator * 2)
        sign = "-" if n < 0 else ""
        n = abs(n)
        whole, frac = n // scale, n % scale
        return "%s%d.%0*d" % (sign, whole, digits, frac)

    def __repr__(self) -> str:                       # pragma: no cover - view
        return "Surd(%s)" % self.render()


