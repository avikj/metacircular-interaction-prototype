# the discrete path family: parallel interfaces with a rational lattice
# --------------------------------------------------------------------------

def lattice(lo, hi, step) -> Tuple[Fraction, ...]:
    """``[lo, lo+step, ..., hi]`` in exact rationals.  Deterministic, finite."""
    lo, hi, step = exact(lo), exact(hi), exact(step)
    if step <= 0:
        raise OpticsError("lattice step must be positive")
    out: List[Fraction] = []
    k = 0
    v = lo
    while v <= hi:
        out.append(v)
        k += 1
        v = lo + step * k
    return tuple(out)


@dataclass(frozen=True)
class InterfaceStack:
    """The discrete path family the runtime optimizes over.

    ``media[0]`` is above ``interfaces[0]``, ``media[i]`` lies between
    ``interfaces[i-1]`` and ``interfaces[i]``, and ``media[-1]`` is below the
    last interface.  A *path* in the family is one lattice crossing point per
    interface; ``source`` sits in the first medium and ``target`` in the last.

    Reachability discipline (CRYSTAL.md Sec.4), stated because it must be:

    * **generated locus** -- rays whose crossings lie on the declared rational
      lattices, and nothing else;
    * **omitted locus** -- every crossing at an irrational abscissa, and every
      rational abscissa off the lattice.  The true Fermat crossing is generally
      in the omitted locus, which is exactly why ``snell_bracket`` exists and
      why no claim here is "the runtime found the physical ray";
    * **completion** -- the continuum family; the group law that extends is
      "OPL is a continuous convex function of the crossing abscissae" (for a
      single interface), and the operation that does *not* extend is
      "enumerate the family".
    """

    source: Vec
    target: Vec
    media: Tuple[Medium, ...]
    boundaries: Tuple[Fraction, ...]
    lattices: Tuple[Tuple[Fraction, ...], ...]

    def __post_init__(self) -> None:
        if len(self.media) != len(self.boundaries) + 1:
            raise OpticsError("k interfaces need k+1 media")
        if len(self.lattices) != len(self.boundaries):
            raise OpticsError("each interface needs one lattice")
        for i in range(1, len(self.boundaries)):
            if not self.boundaries[i] < self.boundaries[i - 1]:
                raise OpticsError("boundaries must descend in y")
        if not self.source.y > self.boundaries[0]:
            raise OpticsError("the source must lie in the first medium")
        if not self.target.y < self.boundaries[-1]:
            raise OpticsError("the target must lie in the last medium")

    @property
    def depth(self) -> int:
        return len(self.boundaries)

    def crossing(self, i: int, x: Fraction) -> Vec:
        return Vec(x, self.boundaries[i])

    def ray(self, xs: Sequence[Fraction]) -> Ray:
        """The ray crossing interface ``i`` at abscissa ``xs[i]``."""
        if len(xs) != self.depth:
            raise OpticsError("need one crossing per interface")
        pts = [self.source] + [self.crossing(i, exact(x)) for i, x in enumerate(xs)]
        pts.append(self.target)
        return Ray(tuple(pts), self.media)

    def opl(self, xs: Sequence[Fraction]) -> Surd:
        return optical_path_length(self.ray(xs))

    def paths(self) -> Iterable[Tuple[Fraction, ...]]:
        """Every member of the family, in a deterministic order."""
        combos: List[Tuple[Fraction, ...]] = [()]
        for lat in self.lattices:
            combos = [c + (x,) for c in combos for x in lat]
        for c in combos:
            yield c

    def size(self) -> int:
        n = 1
        for lat in self.lattices:
            n *= len(lat)
        return n


# --------------------------------------------------------------------------
# Snell, as a measurement of a route -- never as an input to finding one
# --------------------------------------------------------------------------

def sine_to_normal(dx: Fraction, dy: Fraction) -> Surd:
    """``sin`` of the angle between the segment ``(dx, dy)`` and the interface
    normal, signed by ``dx``.  Exact: ``dx / sqrt(dx^2+dy^2) = dx sqrt(m) / m``.

    The interface normal is the ``y`` axis throughout this module.
    """
    dx, dy = exact(dx), exact(dy)
    m = dx * dx + dy * dy
    if m == 0:
        raise OpticsError("a degenerate segment has no angle")
    COUNTERS.bump("optics.sine")
    return Surd.scaled_sqrt(Fraction(dx, m), m)


def snell_residual(stack: InterfaceStack, xs: Sequence[Fraction],
                   interface: int = 0) -> Surd:
    """``n_i sin(theta_i) - n_{i+1} sin(theta_{i+1})`` at one interface, exactly.

    This is a *measurement applied to a route already found*.  It is the exact
    derivative of the OPL with respect to that crossing abscissa, so it is zero
    exactly when the route is stationary in that coordinate -- but nothing in
    the routing machinery consults it, by design and by test.
    """
    ray = stack.ray(xs)
    p_in = ray.points[interface]
    p_mid = ray.points[interface + 1]
    p_out = ray.points[interface + 2]
    a = p_mid.minus(p_in)
    b = p_out.minus(p_mid)
    s1 = sine_to_normal(a.x, a.y).scale(stack.media[interface].index)
    s2 = sine_to_normal(b.x, b.y).scale(stack.media[interface + 1].index)
    COUNTERS.bump("optics.snell_residual")
    return s1 - s2


def reflection_residual(source: Vec, point: Vec, target: Vec,
                        tangent: Vec) -> Surd:
    """The law of reflection at ``point``, as an exact ``Surd`` that is zero
    exactly when the law holds.

    The law says the incident and reflected unit directions have equal
    tangential components:  ``(u.t)/|u| = (v.t)/|v|``, for ``u = P - A`` and
    ``v = B - P``.  Clearing denominators gives

        (u.t) * |v|  -  (v.t) * |u|   =   (u.t) sqrt(v.v) - (v.t) sqrt(u.u)

    which is a two-term ``Surd`` -- so its sign is decided by exactly the
    primitive the brief names, ``a sqrt(x)`` vs ``b sqrt(y)`` via ``a^2 x`` vs
    ``b^2 y``.  No angle, no arcsine, no square root evaluated.

    Like ``snell_residual`` this is a *measurement of a route*, never an input
    to finding one.
    """
    u = point.minus(source)
    v = target.minus(point)
    ut = u.x * tangent.x + u.y * tangent.y
    vt = v.x * tangent.x + v.y * tangent.y
    COUNTERS.bump("optics.reflection_residual")
    return Surd.scaled_sqrt(ut, v.norm2()) - Surd.scaled_sqrt(vt, u.norm2())


def circle_tangent(point: Vec) -> Vec:
    """The tangent to ``x^2+y^2=R^2`` at ``point``: exact, no normalisation."""
    return Vec(-point.y, point.x)


def snell_invariant(stack: InterfaceStack, xs: Sequence[Fraction]) -> Tuple[Surd, ...]:
    """``n sin(theta)`` in every medium along the route.  Snell's law says these
    are all equal; here they are simply *reported*, exactly."""
    ray = stack.ray(xs)
    out: List[Surd] = []
    for i, medium in enumerate(stack.media):
        d = ray.points[i + 1].minus(ray.points[i])
        out.append(sine_to_normal(d.x, d.y).scale(medium.index))
    return tuple(out)


# --------------------------------------------------------------------------
# stationarity -- a second algorithm, deliberately not the optimizer
# --------------------------------------------------------------------------

@dataclass(frozen=True)
class Critical:
    """A stationary point of a discrete family, with its exact classification."""

    index: int
    kind: str                       # "minimum" | "maximum" | "inflection" | "flat"
    value: Surd

    def render(self) -> str:
        return "i=%-4d %-11s opl=%s" % (self.index, self.kind, self.value.render())


def critical_points(values: Sequence[Surd], cyclic: bool = False) -> Tuple[Critical, ...]:
    """Stationary points of a discrete family, by exact sign changes.

    ``d_i = values[i+1] - values[i]``.  A point ``i`` is a discrete critical
    point when ``sign(d_{i-1})`` and ``sign(d_i)`` are not both ``+`` or both
    ``-``; it is a minimum on ``(-, +)``, a maximum on ``(+, -)``, and flat or
    an inflection otherwise.  Every comparison is an exact ``Surd`` sign.

    **This is not the extraction machinery and cannot be made into it.**  It
    enumerates the whole family and inspects local differences; it is an
    ``O(n)`` scan, not a shortest-path search, and it has no analogue at all
    once the family is a graph rather than a line.  That is the honest content
    of the stationary-vs-minimal disanalogy: minimization is a search, and
    stationarity is not.
    """
    n = len(values)
    if n < 3:
        return ()
    diffs: List[int] = []
    span = n if cyclic else n - 1
    for i in range(span):
        j = (i + 1) % n
        diffs.append((values[j] - values[i]).sign())
    out: List[Critical] = []
    rng = range(n) if cyclic else range(1, n - 1)
    for i in rng:
        prev = diffs[(i - 1) % len(diffs)]
        nxt = diffs[i % len(diffs)]
        if prev < 0 and nxt > 0:
            kind = "minimum"
        elif prev > 0 and nxt < 0:
            kind = "maximum"
        elif prev == 0 and nxt == 0:
            kind = "flat"
        elif prev == 0 or nxt == 0:
            kind = "flat"
        else:
            continue                     # strictly monotone through i
        out.append(Critical(index=i, kind=kind, value=values[i]))
    COUNTERS.bump("optics.critical_scan")
    return tuple(out)


# --------------------------------------------------------------------------
# a reflecting arc, generated by the rational chart
# --------------------------------------------------------------------------

@dataclass(frozen=True)
class MirrorArc:
    """Reflection points on the circle ``x^2 + y^2 = R^2``, generated exactly.

    The generated locus is the image of the rational chart

        t  |->  ( R(1-t^2)/(1+t^2),  R(2t)/(1+t^2) )

    over a finite rational lattice of ``t``, **plus** the chart's omitted point
    ``(-R, 0)``, which no finite ``t`` reaches.  That is
    ``notes/RATIONAL_CIRCLE_ATLAS.md``'s exact-finite-address / dense /
    measure-zero situation, restated for a mirror: the group law (rotation by a
    rational point) extends to the whole circle; the enumeration successor does
    not, and the *irrational* reflection points are the omitted locus.

    Points are ordered by increasing ``t`` with the omitted point first, which
    is the cyclic order around the circle, so ``critical_points(..., cyclic=True)``
    is meaningful on the resulting value list.
    """

    radius: Fraction
    ts: Tuple[Fraction, ...]

    @staticmethod
    def of(radius, ts: Sequence) -> "MirrorArc":
        r = exact(radius)
        if r <= 0:
            raise OpticsError("a mirror radius must be positive")
        return MirrorArc(r, tuple(exact(t) for t in ts))

    def points(self) -> Tuple[Vec, ...]:
        out = [Vec(-self.radius, Fraction(0))]        # the chart's omitted point
        for t in self.ts:
            den = 1 + t * t
            out.append(Vec(self.radius * Fraction(1 - t * t, den),
                           self.radius * Fraction(2 * t, den)))
        return tuple(out)

    def on_circle(self, p: Vec) -> bool:
        return p.norm2() == self.radius * self.radius

    def omitted_locus(self) -> str:
        return ("every irrational point of the circle, plus every rational point "
                "whose chart parameter is off the declared lattice; the chart's "
                "own omitted point (-R, 0) is supplied explicitly as the second "
                "chart")
