class IndependenceReport:
    """Result of the fake-locality check."""

    __slots__ = ("ok", "offenders", "checked")

    def __init__(self, ok: bool, offenders: Sequence[Tuple[str, str]],
                 checked: int) -> None:
        self.ok = ok
        self.offenders = tuple(offenders)
        self.checked = checked

    def render(self) -> str:
        if self.ok:
            return ("locality: %d readers re-run against poisoned neighbours, "
                    "all %d readings identical" % (self.checked, self.checked))
        return "locality VIOLATED: " + "; ".join(
            "%s: %s" % (v, why) for v, why in self.offenders)

    def __repr__(self) -> str:                     # pragma: no cover - view
        return "IndependenceReport(ok=%r, %d offenders)" % (
            self.ok, len(self.offenders))


def assert_independent(claim: Claim,
                       readers: Mapping[int, Callable] = None
                       ) -> IndependenceReport:
    """Prove each view is computable without the other three.

    For each view, rebuild the claim with the other three sources replaced by
    ``Poison`` and re-run that view's reader.  The reading must be identical.
    A reader that reaches across raises inside ``Poison``; a reader that reads
    across without raising (because it captured the data in a closure) changes
    nothing here -- so the check is paired, in the suite, with a control that
    plants exactly that and is caught by the ``Poison`` path.
    """
    use = dict(READERS if readers is None else readers)
    offenders = []
    reference = {}
    for v in ALL_VIEWS:
        reference[v] = use[v](claim.sources[v], claim.sites)
    for v in ALL_VIEWS:
        isolated = {w: (claim.sources[w] if w == v
                        else Poison(view_name(w))) for w in ALL_VIEWS}
        try:
            got = use[v](isolated[v], claim.sites)
        except NerveError as exc:
            offenders.append((view_name(v), str(exc)))
            continue
        except Exception as exc:                   # pragma: no cover - defence
            offenders.append((view_name(v), "reader raised %r" % (exc,)))
            continue
        ref = reference[v]
        if got.reading != ref.reading or got.visible != ref.visible:
            offenders.append((view_name(v),
                              "reading changed when the neighbours were removed"))
    return IndependenceReport(not offenders, offenders, len(ALL_VIEWS))


def require_four_views(claim: Claim) -> Tuple[bool, Tuple[str, ...]]:
    """The gate's entry condition: all four views, non-empty, schema-complete.

    Returns ``(ok, complaints)``.  It never raises: a claim that cannot supply
    four views is not thereby false, it is *unassessable*, and the certificate
    says so.
    """
    complaints = []
    for v in ALL_VIEWS:
        src = claim.sources.get(v)
        if src is None:
            complaints.append("view %s is missing" % view_name(v))
            continue
        if isinstance(src, Poison):
            complaints.append("view %s is poisoned" % view_name(v))
            continue
        try:
            section = READERS[v](src, claim.sites)
        except NerveError as exc:
            complaints.append("view %s: %s" % (view_name(v), exc))
            continue
        if not section.visible:
            complaints.append(
                "view %s is blind at every site of the claim" % view_name(v))
    return (not complaints, tuple(complaints))


